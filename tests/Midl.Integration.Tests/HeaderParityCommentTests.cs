using Midl.Analysis;
using Midl.Analysis.Symbols;
using Midl.CodeGen.Header;

namespace Midl.Integration.Tests;

/// <summary>
/// Integration tests verifying that IID seed comment blocks are emitted
/// before interfaces and delegates in the header output.
/// </summary>
public partial class HeaderParityTests
{
    [Fact]
    public void Parity_BasicClass_EmitsInterfaceComment()
    {
        var source = File.ReadAllText(Path.Combine(FixturesDir, "parity_basic_class.idl"));
        var compilation = CompilationHelper.Compile(source);
        var errors = compilation.Diagnostics
            .Where(d => d.Severity == Analysis.Diagnostics.DiagnosticSeverity.Error)
            .ToList();
        Assert.Empty(errors);

        var header = _emitter.Emit(compilation);

        // Synthesized IBasicWidget should have type comment
        Assert.Contains("Interface TestApp.Parity.IBasicWidget", header);
        Assert.Contains("Interface is a part of the implementation of type TestApp.Parity.BasicWidget", header);
        Assert.Contains("automatically generated by MIDLRT", header);
        Assert.Contains("Interface IID generation seed: TestApp.Parity.IBasicWidget:", header);
    }

    [Fact]
    public void Parity_BasicClass_CommentAppearsBeforeGuard()
    {
        var source = File.ReadAllText(Path.Combine(FixturesDir, "parity_basic_class.idl"));
        var compilation = CompilationHelper.Compile(source);
        var header = _emitter.Emit(compilation);

        var commentIdx = header.IndexOf("Interface TestApp.Parity.IBasicWidget");
        var guardIdx = header.IndexOf("#ifndef ____x_TestApp_CParity_CIBasicWidget_INTERFACE_DEFINED__");
        Assert.True(commentIdx >= 0, "Comment should be present");
        Assert.True(guardIdx >= 0, "Guard should be present");
        Assert.True(commentIdx < guardIdx, "Comment must appear before the guard");
    }

    [Fact]
    public void Parity_Delegates_EmitsDelegateComment()
    {
        var source = File.ReadAllText(Path.Combine(FixturesDir, "parity_delegates.idl"));
        var compilation = CompilationHelper.Compile(source);
        var errors = compilation.Diagnostics
            .Where(d => d.Severity == Analysis.Diagnostics.DiagnosticSeverity.Error)
            .ToList();
        Assert.Empty(errors);

        var header = _emitter.Emit(compilation);

        Assert.Contains("Delegate TestApp.Parity.SimpleCallback", header);
        Assert.Contains("Delegate IID generation seed: TestApp.Parity.SimpleCallback:", header);
        Assert.Contains("Delegate TestApp.Parity.MessageHandler", header);
    }

    [Fact]
    public void Parity_Exclusiveto_EmitsExclusiveComment()
    {
        var source = File.ReadAllText(Path.Combine(FixturesDir, "parity_exclusiveto.idl"));
        var compilation = CompilationHelper.Compile(source);
        var errors = compilation.Diagnostics
            .Where(d => d.Severity == Analysis.Diagnostics.DiagnosticSeverity.Error)
            .ToList();
        Assert.Empty(errors);

        var header = _emitter.Emit(compilation);

        // Exclusive interfaces should mention they are part of ExclusiveWidget
        Assert.Contains("Interface is a part of the implementation of type TestApp.Parity.ExclusiveWidget", header);
    }

    [Fact]
    public void Parity_Interfaces_EmitsInterfaceCommentWithoutExclusive()
    {
        var source = File.ReadAllText(Path.Combine(FixturesDir, "parity_interfaces.idl"));
        var compilation = CompilationHelper.Compile(source);
        var errors = compilation.Diagnostics
            .Where(d => d.Severity == Analysis.Diagnostics.DiagnosticSeverity.Error)
            .ToList();
        Assert.Empty(errors);

        var header = _emitter.Emit(compilation);

        // IDataSource is not exclusive — should have comment but no "part of implementation" line
        Assert.Contains("Interface TestApp.Parity.IDataSource", header);
        Assert.Contains("Interface IID generation seed: TestApp.Parity.IDataSource:", header);
    }

    [Fact]
    public void Parity_EmptyInterface_ExplicitUuid_NoSeedComment()
    {
        var source = File.ReadAllText(Path.Combine(FixturesDir, "parity_empty_interface.idl"));
        var compilation = CompilationHelper.Compile(source);
        var errors = compilation.Diagnostics
            .Where(d => d.Severity == Analysis.Diagnostics.DiagnosticSeverity.Error)
            .ToList();
        Assert.Empty(errors);

        var header = _emitter.Emit(compilation);

        // These have explicit UUIDs - should have interface name but no seed
        Assert.Contains("Interface TestApp.Parity.IMarker", header);
        // Explicit UUID means no auto-generated line
        Assert.DoesNotContain("Interface IID generation seed: TestApp.Parity.IMarker:", header);
    }
}
