using Midl.Analysis;
using Midl.CodeGen.Header;

namespace Midl.CodeGen.Tests;

/// <summary>
/// Unit tests for the standard MIDL-style header boilerplate emitted by HeaderEmitter.
/// </summary>
public partial class HeaderEmitterBoilerplateTests
{
    private readonly HeaderEmitter _emitter = new();

    private static Compilation Compile(string source) => CompilationHelper.Compile(source);

    private static string SimpleIdl => @"
        namespace TestApp
        {
            enum Color { Red, Green, Blue };
        }";

    [Fact]
    public void Emit_StartsWithAutoGeneratedComment()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.StartsWith("/* Header file automatically generated", header);
    }

    [Fact]
    public void Emit_ContainsCompilerVersionComment()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("File built with WinMIDL Compiler", header);
    }

    [Fact]
    public void Emit_ContainsPragmaWarningDisable4049()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#pragma warning( disable: 4049 )", header);
    }

    [Fact]
    public void Emit_ContainsRequiredRpcndrVersion()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#ifndef __REQUIRED_RPCNDR_H_VERSION__", header);
        Assert.Contains("#define __REQUIRED_RPCNDR_H_VERSION__ 500", header);
    }

    [Fact]
    public void Emit_ContainsRequiredRpcsalVersion()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#ifndef __REQUIRED_RPCSAL_H_VERSION__", header);
        Assert.Contains("#define __REQUIRED_RPCSAL_H_VERSION__ 100", header);
    }

    [Fact]
    public void Emit_IncludesRpcHeaders()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#include <rpc.h>", header);
        Assert.Contains("#include <rpcndr.h>", header);
    }

    [Fact]
    public void Emit_ChecksRpcndrHVersion()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#ifndef __RPCNDR_H_VERSION__", header);
        Assert.Contains("#error this stub requires an updated version of <rpcndr.h>", header);
    }

    [Fact]
    public void Emit_ContainsComNoWindowsHGuard()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#ifndef COM_NO_WINDOWS_H", header);
        Assert.Contains("#include <windows.h>", header);
        Assert.Contains("#include <ole2.h>", header);
        Assert.Contains("#endif /*COM_NO_WINDOWS_H*/", header);
    }

    [Fact]
    public void Emit_HasDoubleIncludeGuard()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        // Outer guard: __TestApp_h__
        Assert.Contains("#ifndef __TestApp_h__", header);
        Assert.Contains("#define __TestApp_h__", header);
        // Inner guard: __TestApp_p_h__
        Assert.Contains("#ifndef __TestApp_p_h__", header);
        Assert.Contains("#define __TestApp_p_h__", header);
    }

    [Fact]
    public void Emit_PragmaOnceAfterGuardDefines()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        var guardPos = header.IndexOf("#define __TestApp_p_h__");
        var pragmaPos = header.IndexOf("#pragma once");
        Assert.True(guardPos >= 0, "Inner guard define not found");
        Assert.True(pragmaPos >= 0, "#pragma once not found");
        Assert.True(pragmaPos > guardPos, "#pragma once should appear after inner guard define");
    }

    [Fact]
    public void Emit_ContainsNsPrefixCheck()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#if !defined(DISABLE_NS_PREFIX_CHECKS)", header);
        Assert.Contains("#define CHECK_NS_PREFIX_STATE \"never\"", header);
    }

    [Fact]
    public void Emit_ContainsMidlConstIdMacro()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#pragma push_macro(\"MIDL_CONST_ID\")", header);
        Assert.Contains("#undef MIDL_CONST_ID", header);
        Assert.Contains("#define MIDL_CONST_ID const __declspec(selectany)", header);
    }

    [Fact]
    public void Emit_IncludesWinrtbaseHeader()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#include \"winrtbase.h\"", header);
    }

    [Fact]
    public void Emit_FooterPopsConstIdMacro()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#pragma pop_macro(\"MIDL_CONST_ID\")", header);
    }

    [Fact]
    public void Emit_FooterClosesDoubleGuard()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.Contains("#endif // __TestApp_p_h__", header);
        Assert.Contains("#endif // __TestApp_h__", header);
    }

    [Fact]
    public void Emit_FooterOrder_PopMacroBeforeEndifs()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        var popPos = header.IndexOf("#pragma pop_macro(\"MIDL_CONST_ID\")");
        var innerEndif = header.IndexOf("#endif // __TestApp_p_h__");
        var outerEndif = header.IndexOf("#endif // __TestApp_h__");

        Assert.True(popPos < innerEndif, "pop_macro should come before inner #endif");
        Assert.True(innerEndif < outerEndif, "inner #endif should come before outer #endif");
    }

    [Fact]
    public void Emit_BoilerplateBeforeTypes()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        var winrtbasePos = header.IndexOf("#include \"winrtbase.h\"");
        var enumPos = header.IndexOf("enum Color");
        Assert.True(winrtbasePos < enumPos,
            "#include winrtbase.h should appear before type declarations");
    }

    [Fact]
    public void Emit_WithFilename_IncludesFilenameInBanner()
    {
        var header = _emitter.Emit(Compile(SimpleIdl), "test_file.idl");
        Assert.Contains("test_file.idl", header);
    }

    [Fact]
    public void Emit_WithoutFilename_UsesFallbackBanner()
    {
        var header = _emitter.Emit(Compile(SimpleIdl));
        Assert.StartsWith("/* Header file automatically generated", header);
    }

    [Fact]
    public void Emit_DottedNamespace_DoubleGuardUsesUnderscore()
    {
        var compilation = Compile(@"
            namespace My.Company.App
            {
                enum Dummy { A };
            }");
        var header = _emitter.Emit(compilation);

        Assert.Contains("#ifndef __My_Company_App_h__", header);
        Assert.Contains("#define __My_Company_App_h__", header);
        Assert.Contains("#ifndef __My_Company_App_p_h__", header);
        Assert.Contains("#define __My_Company_App_p_h__", header);
        Assert.Contains("#endif // __My_Company_App_p_h__", header);
        Assert.Contains("#endif // __My_Company_App_h__", header);
    }
}
