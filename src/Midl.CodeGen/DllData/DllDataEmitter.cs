using System.Text;
using Midl.Analysis;

namespace Midl.CodeGen.DllData;

/// <summary>
/// Generates dlldata.c for proxy/stub DLL registration.
/// </summary>
public class DllDataEmitter
{
    public string Emit(Compilation compilation)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// dlldata.c -- auto-generated by MIDL compiler");
        sb.AppendLine();
        sb.AppendLine("#define PROXY_CLSID_IS(x) /* empty for now */");
        sb.AppendLine();
        sb.AppendLine("#define REGISTER_PROXY_DLL");
        sb.AppendLine();
        sb.AppendLine("#define ENTRY_PREFIX    Prx");
        sb.AppendLine();
        sb.AppendLine("#include <rpcproxy.h>");
        sb.AppendLine();
        sb.AppendLine("DLLDATA_ROUTINES(aProxyFileList, GET_DLL_CLSID)");
        sb.AppendLine();
        sb.AppendLine("// End of generated dlldata");

        return sb.ToString();
    }

    public void EmitToFile(Compilation compilation, string outputPath)
    {
        var content = Emit(compilation);
        File.WriteAllText(outputPath, content);
    }
}
