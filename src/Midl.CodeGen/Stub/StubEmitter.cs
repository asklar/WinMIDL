using System.Text;
using Midl.Analysis;

namespace Midl.CodeGen.Stub;

/// <summary>
/// Generates minimal proxy/stub skeleton (_p.c) files.
/// Full NDR format string generation is not yet implemented.
/// </summary>
public class StubEmitter
{
    public string Emit(Compilation compilation)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// Proxy/stub file auto-generated by MIDL compiler");
        sb.AppendLine("// Full NDR format string generation is not yet implemented.");
        sb.AppendLine();
        sb.AppendLine("#define USE_STUBLESS_PROXY");
        sb.AppendLine();
        sb.AppendLine("#include <rpcproxy.h>");
        sb.AppendLine();
        sb.AppendLine("// NDR format strings are not used; see ProxyGenerator/StubGenerator for compiled marshaling.");
        sb.AppendLine();
        sb.AppendLine("// End of generated proxy file");

        return sb.ToString();
    }

    public void EmitToFile(Compilation compilation, string outputPath)
    {
        var content = Emit(compilation);
        File.WriteAllText(outputPath, content);
    }
}
