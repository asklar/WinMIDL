using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;

namespace Midl.CodeGen.Proxy;

/// <summary>
/// Generates C++ stub classes implementing IRpcStubBuffer for WinRT interfaces.
/// Each stub receives marshaled calls from the proxy, deserializes parameters,
/// invokes the real server object, and serializes the reply.
/// </summary>
public class StubGenerator
{
    private static readonly Dictionary<string, string> TypeMap = new(StringComparer.Ordinal)
    {
        ["Int16"] = "INT16",
        ["Int32"] = "INT32",
        ["Int64"] = "INT64",
        ["UInt8"] = "BYTE",
        ["UInt16"] = "UINT16",
        ["UInt32"] = "UINT32",
        ["UInt64"] = "UINT64",
        ["Single"] = "FLOAT",
        ["Double"] = "DOUBLE",
        ["Boolean"] = "boolean",
        ["Char"] = "WCHAR",
        ["String"] = "HSTRING",
        ["Guid"] = "GUID",
        ["Object"] = "IInspectable*",
        ["void"] = "void",
        ["HRESULT"] = "HRESULT",
    };

    /// <summary>
    /// Generate C++ stub code for all non-external interfaces in the compilation.
    /// </summary>
    public string Generate(Compilation compilation, bool useExceptions = false)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// Stub file auto-generated by MIDL compiler");
        sb.AppendLine("#pragma once");
        sb.AppendLine();
        WireFormat.EmitConsolidatedIncludes(sb);
        sb.AppendLine("#include \"winmidl/proxy_helpers.h\"");
        sb.AppendLine();
        // Generic IID constants are emitted by ProxyGenerator (shared .cpp file)

        var interfaces = compilation.GetAllTypes()
            .OfType<InterfaceSymbol>()
            .Where(i => !i.IsExternal)
            .ToList();

        var delegates = compilation.GetAllTypes()
            .OfType<DelegateSymbol>()
            .Where(d => !d.IsExternal)
            .ToList();

        var emittedDescriptors = new HashSet<string>();
        foreach (var iface in interfaces)
        {
            EmitStubClass(sb, iface, useExceptions, emittedDescriptors);
        }
        foreach (var del in delegates)
        {
            EmitDelegateStubClass(sb, del, useExceptions);
        }

        return sb.ToString();
    }

    private void EmitStubClass(StringBuilder sb, InterfaceSymbol iface, bool useExceptions, HashSet<string>? emittedDescriptorsGlobal = null)
    {
        var mangledName = MangleName(iface.FullName);
        var className = $"CStub_{mangledName}";
        var iidName = $"IID_{mangledName}";

        // Collect all ABI slots
        var slots = BuildSlotList(iface);

        // Phase 6: Signature folding — emit shared stub shape functions
        var emittedShapes = new HashSet<string>();
        foreach (var slot in slots)
        {
            var proxyParams = slot.Parameters.Select(p =>
                new ProxyParam(p.Name, p.Type, p.Direction == ParameterDirection.Out ? ParamDirection.Out : ParamDirection.In)).ToList();
            var shapeKey = ProxyGenerator.ComputeShapeKey(proxyParams, slot.ReturnType);
            if (emittedShapes.Add(shapeKey))
            {
                sb.AppendLine($"// Shared stub shape: stub_shape_{shapeKey}");
            }
        }

        sb.AppendLine($"class {className} : public winmidl::stub_base_t<{className}> {{");
        sb.AppendLine($"    {mangledName}* m_pServer;");
        sb.AppendLine();
        sb.AppendLine("public:");
        sb.AppendLine($"    {className}() : m_pServer(nullptr) {{}}");
        sb.AppendLine();

        // Connect
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE Connect(IUnknown* pUnkServer) override {");
        sb.AppendLine($"        return pUnkServer->QueryInterface({iidName}, (void**)&m_pServer);");
        sb.AppendLine("    }");

        // Disconnect
        sb.AppendLine("    void STDMETHODCALLTYPE Disconnect() override {");
        sb.AppendLine("        if (m_pServer) { m_pServer->Release(); m_pServer = nullptr; }");
        sb.AppendLine("    }");

        // Invoke
        EmitInvokeDispatch(sb, iface, slots, iidName);

        // Static type info for this interface
        sb.AppendLine($"    static constexpr IID kIIDs[] = {{ {iidName} }};");
        sb.AppendLine($"    static inline const winmidl::type_info_t kTypeInfo = {{ kIIDs, L\"{iface.FullName}\" }};");
        sb.AppendLine();

        // IsIIDSupported — data-driven via type_info
        sb.AppendLine($"    IRpcStubBuffer* STDMETHODCALLTYPE IsIIDSupported(REFIID riid) override {{");
        sb.AppendLine($"        for (const auto& iid : kTypeInfo.iids) {{");
        sb.AppendLine($"            if (iid == riid) {{ AddRef(); return this; }}");
        sb.AppendLine($"        }}");
        sb.AppendLine("        return nullptr;");
        sb.AppendLine("    }");

        // CountRefs
        sb.AppendLine("    ULONG STDMETHODCALLTYPE CountRefs() override { return m_pServer ? 1 : 0; }");

        // DebugServerQueryInterface
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE DebugServerQueryInterface(void** ppv) override {");
        sb.AppendLine($"        return m_pServer ? m_pServer->QueryInterface({iidName}, ppv) : E_NOINTERFACE;");
        sb.AppendLine("    }");

        // DebugServerRelease
        sb.AppendLine("    void STDMETHODCALLTYPE DebugServerRelease(void* pv) override {");
        sb.AppendLine("        if (pv) ((IUnknown*)pv)->Release();");
        sb.AppendLine("    }");

        // QueryInterface entry table — used by stub_base_t<Derived>::QueryInterface
        sb.AppendLine("    static inline const winmidl::qi_entry_t kStubQIEntries[] = {");
        sb.AppendLine("        { IID_IUnknown, 0, false },");
        sb.AppendLine("        { IID_IRpcStubBuffer, 0, false },");
        sb.AppendLine("    };");
        sb.AppendLine();

        // Private per-method invoke handlers
        sb.AppendLine("private:");
        foreach (var slot in slots)
        {
            EmitInvokeHandler(sb, slot, iface, useExceptions);
        }

        sb.AppendLine("};");
        sb.AppendLine();

        // Emit method descriptor tables after the class (file-scope) — deduplicated
        var descSet = emittedDescriptorsGlobal ?? new HashSet<string>();
        if (descSet.Add(mangledName))
        {
            EmitDescriptorTables(sb, iface, slots, mangledName, iidName);
        }
    }

    private void EmitInvokeDispatch(StringBuilder sb, InterfaceSymbol iface, List<StubSlot> slots, string iidName)
    {
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE Invoke(RPCOLEMESSAGE* pMsg, IRpcChannelBuffer* pChannel) override {");
        if (slots.Count == 0)
        {
            sb.AppendLine("        (void)pMsg; (void)pChannel;");
            sb.AppendLine("        return E_UNEXPECTED;");
        }
        else
        {
            sb.AppendLine("        switch (pMsg->iMethod) {");

            foreach (var slot in slots)
            {
                sb.AppendLine($"            case {slot.Index}: return Invoke_{slot.Name}(pMsg, pChannel);");
            }

            sb.AppendLine("            default: return E_UNEXPECTED;");
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
    }

    private void EmitInvokeHandler(StringBuilder sb, StubSlot slot, InterfaceSymbol iface, bool useExceptions)
    {
        var mangledName = MangleName(iface.FullName);
        var iidName = $"IID_{mangledName}";
        bool isAsync = WireFormat.IsAsyncReturnType(slot.ReturnType);

        sb.AppendLine($"    HRESULT Invoke_{slot.Name}(RPCOLEMESSAGE* pMsg, IRpcChannelBuffer* pChannel) {{");

        // Determine in/out/ref params and return type
        var inParams = slot.Parameters.Where(p => p.Direction == ParameterDirection.In).ToList();
        var outParams = slot.Parameters.Where(p => p.Direction == ParameterDirection.Out).ToList();
        var refParams = slot.Parameters.Where(p => p.Direction == ParameterDirection.Ref).ToList();
        var hasRetval = slot.ReturnType.Name != "void";
        bool hasIfaceInParams = inParams.Any(p => WireFormat.IsInterfaceType(p.Type));
        bool hasNonBlittableStructInParams = inParams.Any(p =>
            p.Type.ResolvedSymbol is StructSymbol s && !WireFormat.IsBlittable(s));

        // Declare hr early if needed for interface deserialization or non-blittable struct field deserialization
        if (hasIfaceInParams || hasNonBlittableStructInParams)
        {
            sb.AppendLine("        HRESULT hr;");
        }

        // Deserialize input parameters (including ref array capacity)
        bool hasRequestData = inParams.Count > 0 || refParams.Any(p => p.IsArray);
        if (hasRequestData)
        {
            sb.AppendLine("        BYTE* p = (BYTE*)pMsg->Buffer;");
            foreach (var param in inParams)
            {
                EmitDeserializeParam(sb, param.Type, param.Name, isAsync);
            }
            // Read capacity for ref array params
            foreach (var param in refParams.Where(p => p.IsArray))
            {
                sb.AppendLine($"        UINT32 __{param.Name}Capacity;");
                sb.AppendLine($"        memcpy(&__{param.Name}Capacity, p, sizeof(UINT32)); p += sizeof(UINT32);");
            }
        }

        // Declare ref array temp buffers
        foreach (var param in refParams.Where(p => p.IsArray))
        {
            var elemType = WireFormat.ElementType(param.Type);
            var elemCType = WireFormat.GetCppTypeName(elemType);
            sb.AppendLine($"        {elemCType}* {param.Name} = ({elemCType}*)CoTaskMemAlloc(__{param.Name}Capacity * {WireFormat.GetCppSizeExpression(elemType)});");
            sb.AppendLine($"        UINT32 __{param.Name}Actual = 0;");
        }

        // Declare out parameters
        foreach (var param in outParams)
        {
            if (param.IsArray)
            {
                var elemType = WireFormat.ElementType(param.Type);
                var elemCType = WireFormat.GetCppTypeName(elemType);
                sb.AppendLine($"        UINT32 __{param.Name}Size = 0;");
                sb.AppendLine($"        {elemCType}* {param.Name} = nullptr;");
            }
            else
            {
                var cType = MapType(param.Type);
                if (WireFormat.IsInterfaceType(param.Type))
                    sb.AppendLine($"        {cType} {param.Name} = nullptr;");
                else
                    sb.AppendLine($"        {cType} {param.Name}{{}};");
            }
        }

        // Declare return value
        if (hasRetval)
        {
            if (slot.ReturnType.IsArray)
            {
                var retElemType = WireFormat.ElementType(slot.ReturnType);
                var retElemCType = WireFormat.GetCppTypeName(retElemType);
                sb.AppendLine($"        UINT32 __returnValueSize = 0;");
                sb.AppendLine($"        {retElemCType}* returnValue = nullptr;");
            }
            else
            {
                var retType = MapType(slot.ReturnType);
                if (WireFormat.IsInterfaceType(slot.ReturnType))
                    sb.AppendLine($"        {retType} returnValue = nullptr;");
                else
                    sb.AppendLine($"        {retType} returnValue{{}};");
            }
        }

        // Build server call
        EmitServerCall(sb, slot, inParams, outParams, hasRetval, hrAlreadyDeclared: hasIfaceInParams || hasNonBlittableStructInParams);

        // Serialize reply
        EmitSerializeReply(sb, slot, outParams, hasRetval, iidName, inParams, useExceptions, refParams);

        if (useExceptions)
        {
            sb.AppendLine("        return S_OK;");
            sb.AppendLine("        } catch (HRESULT hr) { return hr; }");
            sb.AppendLine("          catch (...) { return E_FAIL; }");
        }
        else
        {
            sb.AppendLine("        return S_OK;");
        }
        sb.AppendLine("    }");
    }

    private void EmitDeserializeParam(StringBuilder sb, TypeRef typeRef, string name, bool isAsync = false)
    {
        if (typeRef.IsArray)
        {
            var elemType = WireFormat.ElementType(typeRef);
            var elemCType = WireFormat.GetCppTypeName(elemType);
            var sizeVar = $"__{name}Size";
            sb.AppendLine($"        UINT32 {sizeVar};");
            sb.AppendLine($"        {elemCType}* {name};");
            if (elemType.Name == "String")
                sb.AppendLine($"        winmidl::unmarshal_hstring_array(p, &{name}, &{sizeVar});");
            else
                sb.AppendLine($"        winmidl::unmarshal_array(p, &{name}, &{sizeVar});");
            return;
        }

        if (typeRef.Name == "String")
        {
            if (isAsync)
            {
                sb.AppendLine($"        HSTRING {name} = nullptr;");
                sb.AppendLine($"        winmidl::unmarshal_hstring_alloc(p, &{name});");
            }
            else
            {
                sb.AppendLine($"        HSTRING_HEADER {name}_header;");
                sb.AppendLine($"        HSTRING {name} = winmidl::unmarshal_hstring_ref(p, {name}_header);");
            }
        }
        else if (WireFormat.IsInterfaceType(typeRef))
        {
            var cType = MapType(typeRef);
            var iidName = WireFormat.GetInterfaceIidName(typeRef);
            sb.AppendLine($"        {cType} {name} = nullptr;");
            sb.AppendLine($"        hr = winmidl::unmarshal_interface(p, {iidName}, (void**)&{name}); RETURN_IF_FAILED(hr);");
        }
        else if (typeRef.Name == "EventRegistrationToken")
        {
            sb.AppendLine($"        EventRegistrationToken {name};");
            sb.AppendLine($"        winmidl::unmarshal_event_token(p, {name});");
        }
        else if (typeRef.ResolvedSymbol is StructSymbol structSym)
        {
            var cType = MapType(typeRef);
            sb.AppendLine($"        {cType} {name};");
            if (WireFormat.IsBlittable(structSym))
            {
                WireFormat.EmitStructLayoutAsserts(sb, structSym, cType, "        ");
                sb.AppendLine($"        winmidl::unmarshal_struct(p, {name});");
            }
            else
            {
                foreach (var field in structSym.Fields)
                {
                    if (WireFormat.IsNullableValueType(field.Type))
                    {
                        var innerType = WireFormat.GetNullableInnerCppType(field.Type);
                        var boxSlot = WireFormat.HasNullableBoxSlot(field.Type) ? WireFormat.GetNullableBoxSlot(field.Type) : -1;
                        if (boxSlot >= 0)
                            sb.AppendLine($"        hr = winmidl::unmarshal_nullable<{innerType}, {boxSlot}>(p, &{name}.{field.Name}); RETURN_IF_FAILED(hr);");
                        else
                            WireFormat.EmitDeserialize(sb, field.Type, $"{name}.{field.Name}", "p");
                    }
                    else
                    {
                        WireFormat.EmitDeserialize(sb, field.Type, $"{name}.{field.Name}", "p");
                    }
                }
            }
        }
        else if (typeRef.ResolvedSymbol is EnumSymbol)
        {
            var cType = MapType(typeRef);
            sb.AppendLine($"        {cType} {name};");
            sb.AppendLine($"        winmidl::unmarshal_enum(p, {name});");
        }
        else
        {
            var cType = MapType(typeRef);
            sb.AppendLine($"        {cType} {name};");
            var helper = WireFormat.GetUnmarshalHelper(typeRef);
            if (helper != null)
                sb.AppendLine($"        winmidl::{helper}(p, {name});");
            else
            {
                var sizeExpr = WireFormat.GetCppSizeExpression(typeRef);
                sb.AppendLine($"        memcpy(&{name}, p, {sizeExpr}); p += {sizeExpr};");
            }
        }
    }

    private void EmitServerCall(StringBuilder sb, StubSlot slot, List<ParameterSymbol> inParams,
        List<ParameterSymbol> outParams, bool hasRetval, bool hrAlreadyDeclared = false)
    {
        var callArgs = new List<string>();

        foreach (var p in slot.Parameters)
        {
            if (p.IsArray)
            {
                if (p.Direction == ParameterDirection.Out)
                {
                    callArgs.Add($"&__{p.Name}Size");
                    callArgs.Add($"&{p.Name}");
                }
                else if (p.Direction == ParameterDirection.Ref)
                {
                    callArgs.Add($"__{p.Name}Capacity");
                    callArgs.Add(p.Name);
                    callArgs.Add($"&__{p.Name}Actual");
                }
                else
                {
                    callArgs.Add($"__{p.Name}Size");
                    callArgs.Add(p.Name);
                }
            }
            else if (p.Direction == ParameterDirection.Out)
                callArgs.Add($"&{p.Name}");
            else
                callArgs.Add(p.Name);
        }

        if (hasRetval)
        {
            if (slot.ReturnType.IsArray)
            {
                callArgs.Add("&__returnValueSize");
                callArgs.Add("&returnValue");
            }
            else
                callArgs.Add("&returnValue");
        }

        var argStr = string.Join(", ", callArgs);
        if (hrAlreadyDeclared)
            sb.AppendLine($"        hr = m_pServer->{slot.Name}({argStr});");
        else
            sb.AppendLine($"        HRESULT hr = m_pServer->{slot.Name}({argStr});");
    }

    private void EmitSerializeReply(StringBuilder sb, StubSlot slot, List<ParameterSymbol> outParams,
        bool hasRetval, string iidName, List<ParameterSymbol> inParams, bool useExceptions, List<ParameterSymbol>? refParams = null)
    {
        refParams ??= new List<ParameterSymbol>();

        // For HSTRING out params/retval, we need to get their lengths before computing buffer size
        foreach (var p in outParams.Where(p => !p.IsArray && p.Type.Name == "String"))
        {
            sb.AppendLine($"        UINT32 {p.Name}_len = winmidl::hstring_len({p.Name});");
        }
        if (hasRetval && !slot.ReturnType.IsArray && slot.ReturnType.Name == "String")
        {
            sb.AppendLine("        UINT32 returnValue_len = winmidl::hstring_len(returnValue);");
        }

        // Pre-compute marshal sizes for interface-typed out params/retval
        var ifaceOutParams = outParams.Where(p => WireFormat.IsInterfaceType(p.Type))
            .Select(p => (p.Name, p.Type)).ToList();
        if (hasRetval && WireFormat.IsInterfaceType(slot.ReturnType))
            ifaceOutParams.Add(("returnValue", slot.ReturnType));
        if (ifaceOutParams.Count > 0)
        {
            WireFormat.EmitInterfaceMarshalSizeComputation(sb, ifaceOutParams);
        }

        // Check if reply is fixed-size for constexpr optimization
        bool replyFixed = outParams.All(p => WireFormat.IsFixedSize(p.Type))
            && (!hasRetval || WireFormat.IsFixedSize(slot.ReturnType))
            && !refParams.Any(p => p.IsArray);

        if (replyFixed)
        {
            var replySizeParts = new List<string>();
            foreach (var p in outParams)
                replySizeParts.Add(WireFormat.GetCppSizeExpression(p.Type));
            if (hasRetval)
                replySizeParts.Add(WireFormat.GetCppSizeExpression(slot.ReturnType));
            replySizeParts.Add("sizeof(HRESULT)");
            var replySizeExpr = string.Join(" + ", replySizeParts);
            sb.AppendLine($"        static constexpr UINT32 kReplySize = {replySizeExpr};");
            sb.AppendLine($"        pMsg->cbBuffer = kReplySize;");
        }
        else
        {
            var sizeParts = new List<string>();
            // Ref array params contribute actual + elements to reply
            foreach (var p in refParams.Where(p => p.IsArray))
            {
                var elemType = WireFormat.ElementType(p.Type);
                if (elemType.Name == "String")
                    sizeParts.Add($"winmidl::hstring_array_size({p.Name}, __{p.Name}Actual)");
                else
                    sizeParts.Add($"sizeof(UINT32) + __{p.Name}Actual * {WireFormat.GetCppSizeExpression(elemType)}");
            }
            foreach (var p in outParams)
            {
                if (p.IsArray)
                {
                    var elemType = WireFormat.ElementType(p.Type);
                    if (elemType.Name == "String")
                        sizeParts.Add($"winmidl::hstring_array_size({p.Name}, __{p.Name}Size)");
                    else
                        sizeParts.Add($"sizeof(UINT32) + __{p.Name}Size * {WireFormat.GetCppSizeExpression(elemType)}");
                }
                else if (p.Type.Name == "String")
                    sizeParts.Add($"sizeof(UINT32) + {p.Name}_len * sizeof(WCHAR) + sizeof(WCHAR)");
                else if (WireFormat.IsInterfaceType(p.Type))
                    sizeParts.Add($"{p.Name}_marshalSize");
                else
                    sizeParts.Add(WireFormat.GetCppSizeExpression(p.Type));
            }
            if (hasRetval)
            {
                if (slot.ReturnType.IsArray)
                {
                    var retElemType = WireFormat.ElementType(slot.ReturnType);
                    if (retElemType.Name == "String")
                        sizeParts.Add("winmidl::hstring_array_size(returnValue, __returnValueSize)");
                    else
                        sizeParts.Add($"sizeof(UINT32) + __returnValueSize * {WireFormat.GetCppSizeExpression(retElemType)}");
                }
                else if (slot.ReturnType.Name == "String")
                    sizeParts.Add("sizeof(UINT32) + returnValue_len * sizeof(WCHAR) + sizeof(WCHAR)");
                else if (WireFormat.IsInterfaceType(slot.ReturnType))
                    sizeParts.Add("returnValue_marshalSize");
                else
                    sizeParts.Add(WireFormat.GetCppSizeExpression(slot.ReturnType));
            }
            sizeParts.Add("sizeof(HRESULT)");
            sb.AppendLine($"        pMsg->cbBuffer = {string.Join(" + ", sizeParts)};");
        }
        if (useExceptions)
        {
            sb.AppendLine("        try {");
            sb.AppendLine($"        winmidl::throw_if_failed(pChannel->GetBuffer(pMsg, {iidName}));");
        }
        else
        {
            sb.AppendLine($"        HRESULT hrBuf = pChannel->GetBuffer(pMsg, {iidName});");
            // On GetBuffer failure, clean up out-params and ref-params before returning
            bool hasOutCleanup = HasOutParamCleanup(outParams, hasRetval, slot.ReturnType);
            bool hasRefCleanup = refParams.Any(p => p.IsArray);
            if (hasOutCleanup || hasRefCleanup)
            {
                sb.AppendLine("        if (FAILED(hrBuf)) {");
                EmitOutParamCleanup(sb, outParams, hasRetval, slot.ReturnType, "            ");
                foreach (var rp in refParams.Where(p => p.IsArray))
                {
                    var elemType = WireFormat.ElementType(rp.Type);
                    if (elemType.Name == "String")
                    {
                        sb.AppendLine($"            for (UINT32 i = 0; i < __{rp.Name}Actual; i++) WindowsDeleteString({rp.Name}[i]);");
                    }
                    sb.AppendLine($"            CoTaskMemFree({rp.Name});");
                }
                sb.AppendLine("            return hrBuf;");
                sb.AppendLine("        }");
            }
            else
            {
                sb.AppendLine($"        RETURN_IF_FAILED(hrBuf);");
            }
        }

        // Check if we need a pointer
        bool needsPointer = outParams.Count > 0 || hasRetval || refParams.Any(p => p.IsArray);
        if (needsPointer)
        {
            sb.AppendLine("        BYTE* pOut = (BYTE*)pMsg->Buffer;");
        }

        // Serialize ref (FillArray) params into reply: actual + elements
        foreach (var param in refParams.Where(p => p.IsArray))
        {
            var elemType = WireFormat.ElementType(param.Type);
            var actualVar = $"__{param.Name}Actual";
            if (elemType.Name == "String")
                sb.AppendLine($"        winmidl::marshal_hstring_array(pOut, {param.Name}, {actualVar});");
            else
                sb.AppendLine($"        winmidl::marshal_array(pOut, {param.Name}, {actualVar});");
        }

        // Serialize out params using helpers
        foreach (var param in outParams)
        {
            WireFormat.EmitSerializeReplyValue(sb, param.Type, param.Name, "pOut");
        }

        // Serialize return value using helpers
        if (hasRetval)
        {
            WireFormat.EmitSerializeReplyValue(sb, slot.ReturnType, "returnValue", "pOut");
        }

        // Serialize HRESULT
        if (needsPointer)
        {
            sb.AppendLine("        winmidl::marshal_int32(pOut, hr);");
        }
        else
        {
            sb.AppendLine("        memcpy(pMsg->Buffer, &hr, sizeof(HRESULT));");
        }

        // Clean up in-param HSTRING locals
        foreach (var param in inParams)
        {
            if (!param.IsArray && param.Type.Name == "String")
                sb.AppendLine($"        WindowsDeleteString({param.Name});");
        }

        // Clean up in-param array locals
        foreach (var param in inParams)
        {
            if (param.IsArray)
            {
                var elemType = WireFormat.ElementType(param.Type);
                if (elemType.Name == "String")
                {
                    sb.AppendLine($"        for (UINT32 i = 0; i < __{param.Name}Size; i++) WindowsDeleteString({param.Name}[i]);");
                }
                sb.AppendLine($"        CoTaskMemFree({param.Name});");
            }
        }

        // Clean up ref-param (FillArray) temp buffers
        foreach (var param in refParams.Where(p => p.IsArray))
        {
            var elemType = WireFormat.ElementType(param.Type);
            if (elemType.Name == "String")
            {
                sb.AppendLine($"        for (UINT32 i = 0; i < __{param.Name}Actual; i++) WindowsDeleteString({param.Name}[i]);");
            }
            sb.AppendLine($"        CoTaskMemFree({param.Name});");
        }

        // Release in-param interface pointers
        foreach (var param in inParams)
        {
            if (WireFormat.IsInterfaceType(param.Type))
                sb.AppendLine($"        if ({param.Name}) {param.Name}->Release();");
        }

        // Clean up out-params and retval (already serialized into the buffer)
        EmitOutParamCleanup(sb, outParams, hasRetval, slot.ReturnType, "        ");
    }

    /// <summary>
    /// Returns true if there are out-params or retval that need cleanup.
    /// </summary>
    private static bool HasOutParamCleanup(List<ParameterSymbol> outParams, bool hasRetval, TypeRef retType)
    {
        foreach (var p in outParams)
        {
            if (!p.IsArray && p.Type.Name == "String") return true;
            if (WireFormat.IsInterfaceType(p.Type)) return true;
            if (p.IsArray) return true;
        }
        if (hasRetval)
        {
            if (!retType.IsArray && retType.Name == "String") return true;
            if (WireFormat.IsInterfaceType(retType)) return true;
            if (retType.IsArray) return true;
        }
        return false;
    }

    /// <summary>
    /// Emit cleanup code for out-params and retval: HSTRING, interface pointers, and arrays.
    /// Called both on the success path (after serialization) and the failure path (GetBuffer failed).
    /// </summary>
    private static void EmitOutParamCleanup(StringBuilder sb, List<ParameterSymbol> outParams,
        bool hasRetval, TypeRef retType, string indent)
    {
        // Clean up out-param HSTRINGs
        foreach (var param in outParams)
        {
            if (!param.IsArray && param.Type.Name == "String")
                sb.AppendLine($"{indent}WindowsDeleteString({param.Name});");
        }
        if (hasRetval && !retType.IsArray && retType.Name == "String")
        {
            sb.AppendLine($"{indent}WindowsDeleteString(returnValue);");
        }

        // Release out-param interface pointers
        foreach (var param in outParams)
        {
            if (WireFormat.IsInterfaceType(param.Type))
                sb.AppendLine($"{indent}if ({param.Name}) {param.Name}->Release();");
        }
        if (hasRetval && WireFormat.IsInterfaceType(retType))
        {
            sb.AppendLine($"{indent}if (returnValue) returnValue->Release();");
        }

        // Clean up out-param arrays
        foreach (var param in outParams)
        {
            if (param.IsArray)
            {
                var elemType = WireFormat.ElementType(param.Type);
                if (elemType.Name == "String")
                {
                    sb.AppendLine($"{indent}for (UINT32 i = 0; i < __{param.Name}Size; i++) WindowsDeleteString({param.Name}[i]);");
                }
                sb.AppendLine($"{indent}CoTaskMemFree({param.Name});");
            }
        }
        if (hasRetval && retType.IsArray)
        {
            var retElemType = WireFormat.ElementType(retType);
            if (retElemType.Name == "String")
            {
                sb.AppendLine($"{indent}for (UINT32 i = 0; i < __returnValueSize; i++) WindowsDeleteString(returnValue[i]);");
            }
            sb.AppendLine($"{indent}CoTaskMemFree(returnValue);");
        }
    }

    private void EmitDescriptorTables(StringBuilder sb, InterfaceSymbol iface, List<StubSlot> slots, string mangledName, string iidName)
    {
        if (slots.Count == 0)
            return;

        // Use "stub_" prefix to avoid collision with proxy descriptor tables
        var prefix = $"stub_{mangledName}";

        // Per-method param descriptor arrays
        foreach (var slot in slots)
        {
            var allParams = new List<(TypeRef Type, string Dir)>();
            foreach (var p in slot.Parameters)
            {
                var dir = p.Direction == ParameterDirection.Out ? "winmidl::param_dir::dir_out" : "winmidl::param_dir::dir_in";
                allParams.Add((p.Type, dir));
            }
            if (slot.ReturnType.Name != "void")
            {
                allParams.Add((slot.ReturnType, "winmidl::param_dir::dir_retval"));
            }

            if (allParams.Count > 0)
            {
                sb.AppendLine($"static constexpr winmidl::param_descriptor {prefix}_{slot.Name}_params[] = {{");
                foreach (var (type, dir) in allParams)
                {
                    var typeEnum = WireFormat.GetParamTypeEnum(type) ?? "winmidl::param_type::t_int32";
                    sb.AppendLine($"    {{ {typeEnum}, {dir} }},");
                }
                sb.AppendLine("};");
            }
        }

        // Method descriptor table
        sb.AppendLine($"static constexpr winmidl::method_descriptor {prefix}_methods[] = {{");
        foreach (var slot in slots)
        {
            var paramCount = slot.Parameters.Count + (slot.ReturnType.Name != "void" ? 1 : 0);
            var paramsRef = paramCount > 0 ? $"{prefix}_{slot.Name}_params" : "nullptr";
            sb.AppendLine($"    {{ {slot.Index}, \"{slot.Name}\", {paramsRef}, {paramCount} }},");
        }
        sb.AppendLine("};");

        // Interface descriptor
        sb.AppendLine($"static constexpr winmidl::interface_descriptor {prefix}_desc = {{");
        sb.AppendLine($"    &{iidName}, {prefix}_methods, {slots.Count}");
        sb.AppendLine("};");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits a stub class for a delegate type. Delegates are IUnknown-based COM interfaces
    /// with a single Invoke method at vtable slot 3.
    /// </summary>
    private void EmitDelegateStubClass(StringBuilder sb, DelegateSymbol del, bool useExceptions)
    {
        var mangledName = MangleName(del.FullName);
        var className = $"CStub_{mangledName}";
        var iidName = $"IID_{mangledName}";

        // Delegate has a single Invoke method at slot 3 (IUnknown-based)
        int invokeSlot = WireFormat.GetFirstUserSlot(isInspectable: false);
        var slots = new List<StubSlot>
        {
            new StubSlot
            {
                Index = invokeSlot,
                Name = "Invoke",
                Parameters = del.Parameters,
                ReturnType = del.ReturnType,
            }
        };

        sb.AppendLine($"// Stub for delegate {del.FullName}");
        sb.AppendLine($"class {className} : public winmidl::stub_base_t<{className}> {{");
        sb.AppendLine($"    {mangledName}* m_pServer;");
        sb.AppendLine();
        sb.AppendLine("public:");
        sb.AppendLine($"    {className}() : m_pServer(nullptr) {{}}");
        sb.AppendLine();

        // Connect
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE Connect(IUnknown* pUnkServer) override {");
        sb.AppendLine($"        return pUnkServer->QueryInterface({iidName}, (void**)&m_pServer);");
        sb.AppendLine("    }");

        // Disconnect
        sb.AppendLine("    void STDMETHODCALLTYPE Disconnect() override {");
        sb.AppendLine("        if (m_pServer) { m_pServer->Release(); m_pServer = nullptr; }");
        sb.AppendLine("    }");

        // Invoke dispatch — single slot
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE Invoke(RPCOLEMESSAGE* pMsg, IRpcChannelBuffer* pChannel) override {");
        sb.AppendLine($"        if (pMsg->iMethod == {invokeSlot}) return Invoke_Invoke(pMsg, pChannel);");
        sb.AppendLine("        return E_UNEXPECTED;");
        sb.AppendLine("    }");

        // Static type info
        sb.AppendLine($"    static constexpr IID kIIDs[] = {{ {iidName} }};");
        sb.AppendLine($"    static inline const winmidl::type_info_t kTypeInfo = {{ kIIDs, L\"{del.FullName}\" }};");
        sb.AppendLine();

        // IsIIDSupported
        sb.AppendLine($"    IRpcStubBuffer* STDMETHODCALLTYPE IsIIDSupported(REFIID riid) override {{");
        sb.AppendLine($"        for (const auto& iid : kTypeInfo.iids) {{");
        sb.AppendLine($"            if (iid == riid) {{ AddRef(); return this; }}");
        sb.AppendLine($"        }}");
        sb.AppendLine("        return nullptr;");
        sb.AppendLine("    }");

        // CountRefs
        sb.AppendLine("    ULONG STDMETHODCALLTYPE CountRefs() override { return m_pServer ? 1 : 0; }");

        // DebugServerQueryInterface
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE DebugServerQueryInterface(void** ppv) override {");
        sb.AppendLine($"        return m_pServer ? m_pServer->QueryInterface({iidName}, ppv) : E_NOINTERFACE;");
        sb.AppendLine("    }");

        // DebugServerRelease
        sb.AppendLine("    void STDMETHODCALLTYPE DebugServerRelease(void* pv) override {");
        sb.AppendLine("        if (pv) ((IUnknown*)pv)->Release();");
        sb.AppendLine("    }");

        // QueryInterface entry table — used by stub_base_t<Derived>::QueryInterface
        sb.AppendLine("    static inline const winmidl::qi_entry_t kStubQIEntries[] = {");
        sb.AppendLine("        { IID_IUnknown, 0, false },");
        sb.AppendLine("        { IID_IRpcStubBuffer, 0, false },");
        sb.AppendLine("    };");
        sb.AppendLine();

        // Private invoke handler for the single Invoke method
        sb.AppendLine("private:");
        EmitInvokeHandler(sb, slots[0], mangledName, iidName, useExceptions);

        sb.AppendLine("};");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits an invoke handler for a delegate stub slot.
    /// Reuses the same serialization logic as interface stubs.
    /// </summary>
    private void EmitInvokeHandler(StringBuilder sb, StubSlot slot, string mangledName, string iidName, bool useExceptions)
    {
        sb.AppendLine($"    HRESULT Invoke_{slot.Name}(RPCOLEMESSAGE* pMsg, IRpcChannelBuffer* pChannel) {{");

        var inParams = slot.Parameters.Where(p => p.Direction == ParameterDirection.In).ToList();
        var outParams = slot.Parameters.Where(p => p.Direction == ParameterDirection.Out).ToList();
        var refParams = slot.Parameters.Where(p => p.Direction == ParameterDirection.Ref).ToList();
        var hasRetval = slot.ReturnType.Name != "void";
        bool hasIfaceInParams = inParams.Any(p => WireFormat.IsInterfaceType(p.Type));
        bool hasNonBlittableStructInParams = inParams.Any(p =>
            p.Type.ResolvedSymbol is StructSymbol s && !WireFormat.IsBlittable(s));

        if (hasIfaceInParams || hasNonBlittableStructInParams)
        {
            sb.AppendLine("        HRESULT hr;");
        }

        // Deserialize input parameters (including ref array capacity)
        bool hasRequestData = inParams.Count > 0 || refParams.Any(p => p.IsArray);
        if (hasRequestData)
        {
            sb.AppendLine("        BYTE* p = (BYTE*)pMsg->Buffer;");
            foreach (var param in inParams)
            {
                EmitDeserializeParam(sb, param.Type, param.Name);
            }
            foreach (var param in refParams.Where(p => p.IsArray))
            {
                sb.AppendLine($"        UINT32 __{param.Name}Capacity;");
                sb.AppendLine($"        memcpy(&__{param.Name}Capacity, p, sizeof(UINT32)); p += sizeof(UINT32);");
            }
        }

        // Declare ref array temp buffers
        foreach (var param in refParams.Where(p => p.IsArray))
        {
            var elemType = WireFormat.ElementType(param.Type);
            var elemCType = WireFormat.GetCppTypeName(elemType);
            sb.AppendLine($"        {elemCType}* {param.Name} = ({elemCType}*)CoTaskMemAlloc(__{param.Name}Capacity * {WireFormat.GetCppSizeExpression(elemType)});");
            sb.AppendLine($"        UINT32 __{param.Name}Actual = 0;");
        }

        // Declare out parameters
        foreach (var param in outParams)
        {
            if (param.IsArray)
            {
                var elemType = WireFormat.ElementType(param.Type);
                var elemCType = WireFormat.GetCppTypeName(elemType);
                sb.AppendLine($"        UINT32 __{param.Name}Size = 0;");
                sb.AppendLine($"        {elemCType}* {param.Name} = nullptr;");
            }
            else
            {
                var cType = MapType(param.Type);
                if (WireFormat.IsInterfaceType(param.Type))
                    sb.AppendLine($"        {cType} {param.Name} = nullptr;");
                else
                    sb.AppendLine($"        {cType} {param.Name}{{}};");
            }
        }

        // Declare return value
        if (hasRetval)
        {
            if (slot.ReturnType.IsArray)
            {
                var retElemType = WireFormat.ElementType(slot.ReturnType);
                var retElemCType = WireFormat.GetCppTypeName(retElemType);
                sb.AppendLine($"        UINT32 __returnValueSize = 0;");
                sb.AppendLine($"        {retElemCType}* returnValue = nullptr;");
            }
            else
            {
                var retType = MapType(slot.ReturnType);
                if (WireFormat.IsInterfaceType(slot.ReturnType))
                    sb.AppendLine($"        {retType} returnValue = nullptr;");
                else
                    sb.AppendLine($"        {retType} returnValue{{}};");
            }
        }

        // Build server call
        EmitServerCall(sb, slot, inParams, outParams, hasRetval, hrAlreadyDeclared: hasIfaceInParams || hasNonBlittableStructInParams);

        // Serialize reply
        EmitSerializeReply(sb, slot, outParams, hasRetval, iidName, inParams, useExceptions, refParams);

        if (useExceptions)
        {
            sb.AppendLine("        return S_OK;");
            sb.AppendLine("        } catch (HRESULT hr) { return hr; }");
            sb.AppendLine("          catch (...) { return E_FAIL; }");
        }
        else
        {
            sb.AppendLine("        return S_OK;");
        }
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Build the list of ABI slots for an interface.
    /// IUnknown: 0-2, IInspectable: 3-5, user methods: 6+
    /// </summary>
    private static List<StubSlot> BuildSlotList(InterfaceSymbol iface)
    {
        var slots = new List<StubSlot>();
        int index = WireFormat.GetFirstUserSlot(isInspectable: true);

        foreach (var member in iface.Members)
        {
            switch (member)
            {
                case PropertySymbol prop:
                    if (prop.HasGetter)
                    {
                        slots.Add(new StubSlot
                        {
                            Index = index++,
                            Name = $"get_{prop.Name}",
                            Parameters = [],
                            ReturnType = prop.Type,
                        });
                    }
                    if (prop.HasSetter)
                    {
                        slots.Add(new StubSlot
                        {
                            Index = index++,
                            Name = $"put_{prop.Name}",
                            Parameters =
                            [
                                new ParameterSymbol("value", null) { Type = prop.Type, Direction = ParameterDirection.In }
                            ],
                            ReturnType = TypeRef.Void,
                        });
                    }
                    break;

                case MethodSymbol method:
                    slots.Add(new StubSlot
                    {
                        Index = index++,
                        Name = method.Name,
                        Parameters = method.Parameters,
                        ReturnType = method.ReturnType,
                    });
                    break;

                case EventSymbol evt:
                    // add_EventName: takes delegate handler (in), returns EventRegistrationToken (out retval)
                    slots.Add(new StubSlot
                    {
                        Index = index++,
                        Name = $"add_{evt.Name}",
                        Parameters =
                        [
                            new ParameterSymbol("handler", null) { Type = evt.DelegateType, Direction = ParameterDirection.In }
                        ],
                        ReturnType = new TypeRef("EventRegistrationToken"),
                    });
                    // remove_EventName: takes EventRegistrationToken (in), returns void
                    slots.Add(new StubSlot
                    {
                        Index = index++,
                        Name = $"remove_{evt.Name}",
                        Parameters =
                        [
                            new ParameterSymbol("token", null) { Type = new TypeRef("EventRegistrationToken"), Direction = ParameterDirection.In }
                        ],
                        ReturnType = TypeRef.Void,
                    });
                    break;
            }
        }

        return slots;
    }

    internal static string MapType(TypeRef typeRef)
    {
        if (typeRef.Name == "void")
            return "void";

        if (TypeMap.TryGetValue(typeRef.Name, out var mapped))
            return mapped;

        // Parameterized interface/delegate instantiations → IInspectable*
        if (typeRef.TypeArguments.Count > 0 && typeRef.ResolvedSymbol is InterfaceSymbol or DelegateSymbol)
            return "IInspectable*";

        if (typeRef.ResolvedSymbol is InterfaceSymbol or DelegateSymbol)
            return $"{MangleName(typeRef.ResolvedSymbol.FullName)}*";

        // RuntimeClass: ABI uses the default interface pointer type
        if (typeRef.ResolvedSymbol is RuntimeClassSymbol rc && rc.DefaultInterface is { } defaultIface)
            return $"{MangleName(defaultIface.FullName)}*";

        if (typeRef.ResolvedSymbol is EnumSymbol or StructSymbol)
            return typeRef.ResolvedSymbol.Name;

        return typeRef.Name;
    }

    internal static string MangleName(string fullName)
    {
        return "__x_" + fullName.Replace(".", "_");
    }

    private class StubSlot
    {
        public int Index { get; init; }
        public required string Name { get; init; }
        public required IReadOnlyList<ParameterSymbol> Parameters { get; init; }
        public required TypeRef ReturnType { get; init; }
    }
