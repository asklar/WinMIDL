using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;
using Midl.CodeGen.Header;

namespace Midl.CodeGen.Proxy;

/// <summary>
/// Generates C++ proxy classes that implement IRpcProxyBuffer for WinRT interface marshaling.
/// Each proxy class implements both the target interface and IRpcProxyBuffer,
/// replacing NDR with direct compiled serialization.
/// </summary>
public class ProxyGenerator
{
    // IUnknown occupies vtable slots 0-2, IInspectable 3-5, user methods start at 6
    private const int UserMethodStartSlot = 6;

    public string Generate(Compilation compilation)
    {
        var sb = new StringBuilder();
        EmitPrologue(sb);

        foreach (var symbol in compilation.GetAllTypes().Where(t => !t.IsExternal))
        {
            if (symbol is InterfaceSymbol iface)
            {
                EmitProxyClass(sb, iface);
            }
        }

        EmitEpilogue(sb);
        return sb.ToString();
    }

    public void GenerateToFile(Compilation compilation, string outputPath)
    {
        var content = Generate(compilation);
        Directory.CreateDirectory(Path.GetDirectoryName(outputPath) ?? ".");
        File.WriteAllText(outputPath, content);
    }

    private static void EmitPrologue(StringBuilder sb)
    {
        sb.AppendLine("// Proxy classes auto-generated by MIDL compiler");
        sb.AppendLine("// Direct compiled serialization — replaces NDR format strings");
        sb.AppendLine();
        sb.AppendLine("#include <windows.h>");
        sb.AppendLine("#include <objidl.h>");
        sb.AppendLine("#include <rpcproxy.h>");
        sb.AppendLine("#include <winstring.h>");
        sb.AppendLine("#include <inspectable.h>");
        sb.AppendLine();
    }

    private static void EmitEpilogue(StringBuilder sb)
    {
        sb.AppendLine("// End of generated proxy file");
    }

    internal static void EmitProxyClass(StringBuilder sb, InterfaceSymbol iface)
    {
        var mangledName = HeaderEmitter.MangleName(iface.FullName);
        var className = $"C{iface.Name}Proxy";
        var iidName = $"IID_{mangledName}";

        sb.AppendLine($"// Proxy for {iface.FullName}");
        sb.AppendLine($"class {className} : public {mangledName}, public IRpcProxyBuffer {{");
        sb.AppendLine("    IUnknown* m_pUnkOuter;");
        sb.AppendLine("    IRpcChannelBuffer* m_pChannel;");
        sb.AppendLine("    LONG m_cRef;");
        sb.AppendLine();
        sb.AppendLine("public:");

        // Constructor
        sb.AppendLine($"    {className}(IUnknown* pUnkOuter) : m_pUnkOuter(pUnkOuter), m_pChannel(nullptr), m_cRef(1) {{}}");
        sb.AppendLine();

        // IRpcProxyBuffer methods
        EmitConnect(sb);
        EmitDisconnect(sb);
        EmitQueryInterface(sb, mangledName, iidName);
        EmitAddRef(sb);
        EmitRelease(sb, className);

        // IInspectable forwarding
        EmitIInspectable(sb);

        // Interface methods
        var methods = CollectInterfaceMethods(iface);
        int slot = UserMethodStartSlot;
        foreach (var (methodName, parameters, returnType, memberKind) in methods)
        {
            EmitProxyMethod(sb, iface, methodName, parameters, returnType, memberKind, mangledName, slot);
            slot++;
        }

        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitConnect(StringBuilder sb)
    {
        sb.AppendLine("    // IRpcProxyBuffer::Connect");
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE Connect(IRpcChannelBuffer* pChannel) override {");
        sb.AppendLine("        m_pChannel = pChannel;");
        sb.AppendLine("        if (pChannel) pChannel->AddRef();");
        sb.AppendLine("        return S_OK;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitDisconnect(StringBuilder sb)
    {
        sb.AppendLine("    // IRpcProxyBuffer::Disconnect");
        sb.AppendLine("    void STDMETHODCALLTYPE Disconnect() override {");
        sb.AppendLine("        if (m_pChannel) { m_pChannel->Release(); m_pChannel = nullptr; }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitQueryInterface(StringBuilder sb, string mangledName, string iidName)
    {
        sb.AppendLine("    // IUnknown::QueryInterface");
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE QueryInterface(REFIID riid, void** ppv) override {");
        sb.AppendLine("        if (riid == IID_IUnknown || riid == IID_IRpcProxyBuffer)");
        sb.AppendLine("            { *ppv = static_cast<IRpcProxyBuffer*>(this); AddRef(); return S_OK; }");
        sb.AppendLine($"        if (riid == {iidName})");
        sb.AppendLine($"            {{ *ppv = static_cast<{mangledName}*>(this); AddRef(); return S_OK; }}");
        sb.AppendLine("        *ppv = nullptr; return E_NOINTERFACE;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitAddRef(StringBuilder sb)
    {
        sb.AppendLine("    // IUnknown::AddRef");
        sb.AppendLine("    ULONG STDMETHODCALLTYPE AddRef() override { return InterlockedIncrement(&m_cRef); }");
        sb.AppendLine();
    }

    private static void EmitRelease(StringBuilder sb, string className)
    {
        sb.AppendLine("    // IUnknown::Release");
        sb.AppendLine("    ULONG STDMETHODCALLTYPE Release() override {");
        sb.AppendLine("        ULONG c = InterlockedDecrement(&m_cRef);");
        sb.AppendLine("        if (c == 0) delete this;");
        sb.AppendLine("        return c;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitIInspectable(StringBuilder sb)
    {
        sb.AppendLine("    // IInspectable (forwarded to outer)");
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE GetIids(ULONG* iidCount, IID** iids) override {");
        sb.AppendLine("        IInspectable* pInsp; HRESULT hr = m_pUnkOuter->QueryInterface(IID_IInspectable, (void**)&pInsp);");
        sb.AppendLine("        if (SUCCEEDED(hr)) { hr = pInsp->GetIids(iidCount, iids); pInsp->Release(); }");
        sb.AppendLine("        return hr;");
        sb.AppendLine("    }");
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE GetRuntimeClassName(HSTRING* className) override {");
        sb.AppendLine("        IInspectable* pInsp; HRESULT hr = m_pUnkOuter->QueryInterface(IID_IInspectable, (void**)&pInsp);");
        sb.AppendLine("        if (SUCCEEDED(hr)) { hr = pInsp->GetRuntimeClassName(className); pInsp->Release(); }");
        sb.AppendLine("        return hr;");
        sb.AppendLine("    }");
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE GetTrustLevel(TrustLevel* trustLevel) override {");
        sb.AppendLine("        IInspectable* pInsp; HRESULT hr = m_pUnkOuter->QueryInterface(IID_IInspectable, (void**)&pInsp);");
        sb.AppendLine("        if (SUCCEEDED(hr)) { hr = pInsp->GetTrustLevel(trustLevel); pInsp->Release(); }");
        sb.AppendLine("        return hr;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>
    /// Collects all ABI methods from an interface in vtable order:
    /// properties → getter then setter, events → add_ then remove_, methods in declaration order.
    /// </summary>
    internal static List<(string Name, List<ProxyParam> Params, TypeRef ReturnType, MemberKind Kind)> CollectInterfaceMethods(InterfaceSymbol iface)
    {
        var methods = new List<(string Name, List<ProxyParam> Params, TypeRef ReturnType, MemberKind Kind)>();

        foreach (var member in iface.Members)
        {
            switch (member)
            {
                case PropertySymbol prop:
                    if (prop.HasGetter)
                    {
                        methods.Add(($"get_{prop.Name}",
                            [],
                            prop.Type,
                            MemberKind.PropertyGetter));
                    }
                    if (prop.HasSetter)
                    {
                        methods.Add(($"put_{prop.Name}",
                            [new ProxyParam(prop.Name.ToLowerInvariant(), prop.Type, ParamDirection.In)],
                            TypeRef.Void,
                            MemberKind.PropertySetter));
                    }
                    break;

                case MethodSymbol method:
                    var methodParams = method.Parameters.Select(p =>
                        new ProxyParam(p.Name, p.Type,
                            p.Direction == ParameterDirection.Out ? ParamDirection.Out : ParamDirection.In))
                        .ToList();
                    methods.Add((method.Name, methodParams, method.ReturnType, MemberKind.Method));
                    break;

                case EventSymbol evt:
                    methods.Add(($"add_{evt.Name}",
                        [new ProxyParam("handler", evt.DelegateType, ParamDirection.In)],
                        new TypeRef("EventRegistrationToken"),
                        MemberKind.EventAdd));
                    methods.Add(($"remove_{evt.Name}",
                        [new ProxyParam("token", new TypeRef("EventRegistrationToken"), ParamDirection.In)],
                        TypeRef.Void,
                        MemberKind.EventRemove));
                    break;
            }
        }

        return methods;
    }

    private static void EmitProxyMethod(
        StringBuilder sb,
        InterfaceSymbol iface,
        string methodName,
        List<ProxyParam> parameters,
        TypeRef returnType,
        MemberKind memberKind,
        string mangledName,
        int vtableSlot)
    {
        // Build C++ signature
        var sigParts = new List<string>();
        foreach (var p in parameters)
        {
            var cType = HeaderEmitter.MapType(p.Type);
            if (p.Direction == ParamDirection.Out)
                sigParts.Add($"{cType}* {p.Name}");
            else
                sigParts.Add($"{cType} {p.Name}");
        }

        bool hasRetval = returnType.Name != "void";
        if (hasRetval)
        {
            var retCType = HeaderEmitter.MapType(returnType);
            sigParts.Add($"{retCType}* result");
        }

        var signature = string.Join(", ", sigParts);
        var iidName = $"IID_{mangledName}";

        sb.AppendLine($"    // {methodName} (vtable slot {vtableSlot})");
        sb.AppendLine($"    HRESULT STDMETHODCALLTYPE {methodName}({signature}) override {{");
        sb.AppendLine("        if (!m_pChannel) return RPC_E_DISCONNECTED;");
        sb.AppendLine("        RPCOLEMESSAGE msg = {};");
        sb.AppendLine($"        msg.iMethod = {vtableSlot};");

        // Compute buffer size for input params
        var inParams = parameters.Where(p => p.Direction == ParamDirection.In).ToList();
        var bufferSizeExpr = ComputeBufferSize(inParams);
        sb.AppendLine($"        msg.cbBuffer = {bufferSizeExpr};");

        sb.AppendLine($"        HRESULT hr = m_pChannel->GetBuffer(&msg, {iidName});");
        sb.AppendLine("        if (FAILED(hr)) return hr;");

        // Serialize input params
        if (inParams.Count > 0)
        {
            sb.AppendLine("        BYTE* p = (BYTE*)msg.Buffer;");
            foreach (var p in inParams)
            {
                EmitSerialize(sb, p.Name, p.Type);
            }
        }

        sb.AppendLine("        ULONG status;");
        sb.AppendLine("        hr = m_pChannel->SendReceive(&msg, &status);");
        sb.AppendLine("        if (FAILED(hr)) return hr;");

        // Deserialize reply
        var outParams = parameters.Where(p => p.Direction == ParamDirection.Out).ToList();
        bool needsReadPointer = hasRetval || outParams.Count > 0;

        if (needsReadPointer)
        {
            sb.AppendLine("        BYTE* pReply = (BYTE*)msg.Buffer;");
        }

        // Deserialize out params
        foreach (var p in outParams)
        {
            EmitDeserialize(sb, p.Name, p.Type, isPointer: true);
        }

        // Deserialize retval
        if (hasRetval)
        {
            EmitDeserialize(sb, "result", returnType, isPointer: true);
        }

        // Deserialize trailing HRESULT
        sb.AppendLine("        HRESULT retHr; memcpy(&retHr, pReply, 4);");
        sb.AppendLine("        m_pChannel->FreeBuffer(&msg);");
        sb.AppendLine("        return retHr;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>
    /// Computes the C++ expression for the buffer size needed to serialize the given parameters.
    /// </summary>
    internal static string ComputeBufferSize(List<ProxyParam> inParams)
    {
        if (inParams.Count == 0)
            return "0";

        var parts = new List<string>();
        foreach (var p in inParams)
        {
            parts.Add(GetTypeSize(p.Type));
        }

        return string.Join(" + ", parts);
    }

    /// <summary>
    /// Returns a C++ expression for the serialized size of a type.
    /// </summary>
    internal static string GetTypeSize(TypeRef type)
    {
        var name = type.Name;

        // Primitives
        if (name is "Boolean" or "UInt8")
            return "1";
        if (name is "Int16" or "UInt16" or "Char")
            return "2";
        if (name is "Int32" or "UInt32" or "Single" or "HRESULT")
            return "4";
        if (name is "Int64" or "UInt64" or "Double")
            return "8";
        if (name is "Guid")
            return "16";

        // Enum is always 4 bytes (as int)
        if (type.ResolvedSymbol is EnumSymbol)
            return "4";

        // HSTRING: dynamic, but we use expression
        if (name is "String")
            return "4 + WindowsGetStringLen({0}) * 2";

        // EventRegistrationToken: 8 bytes (INT64)
        if (name is "EventRegistrationToken")
            return "8";

        // Struct: sum of field sizes
        if (type.ResolvedSymbol is StructSymbol structSym)
        {
            return ComputeStructSize(structSym);
        }

        // Interface/delegate pointers can't be directly marshaled via memcpy
        // For now, return sizeof(void*) as placeholder
        return "sizeof(void*)";
    }

    /// <summary>
    /// Computes the size expression for a struct by summing its field sizes.
    /// </summary>
    internal static string ComputeStructSize(StructSymbol structSym)
    {
        if (structSym.Fields.Count == 0)
            return "0";

        var fieldSizes = structSym.Fields.Select(f => GetTypeSizeSimple(f.Type)).ToList();
        var total = fieldSizes.Sum();
        return total.ToString();
    }

    /// <summary>
    /// Returns a numeric size for types that have fixed sizes. Used for struct field size computation.
    /// </summary>
    private static int GetTypeSizeSimple(TypeRef type)
    {
        var name = type.Name;
        if (name is "Boolean" or "UInt8") return 1;
        if (name is "Int16" or "UInt16" or "Char") return 2;
        if (name is "Int32" or "UInt32" or "Single" or "HRESULT") return 4;
        if (name is "Int64" or "UInt64" or "Double") return 8;
        if (name is "Guid") return 16;
        if (name is "EventRegistrationToken") return 8;
        if (type.ResolvedSymbol is EnumSymbol) return 4;
        if (type.ResolvedSymbol is StructSymbol s)
            return s.Fields.Sum(f => GetTypeSizeSimple(f.Type));
        return 8; // fallback for pointers
    }

    /// <summary>
    /// Emits C++ code to serialize a parameter into the RPC buffer.
    /// Assumes a BYTE* p variable is in scope and advances it.
    /// </summary>
    internal static void EmitSerialize(StringBuilder sb, string paramName, TypeRef type)
    {
        var typeName = type.Name;

        if (typeName is "String")
        {
            // HSTRING serialization: [4-byte char count][UTF-16 chars]
            sb.AppendLine($"        UINT32 {paramName}_len = WindowsGetStringLen({paramName});");
            sb.AppendLine($"        memcpy(p, &{paramName}_len, 4); p += 4;");
            sb.AppendLine($"        PCWSTR {paramName}_raw = WindowsGetStringRawBuffer({paramName}, nullptr);");
            sb.AppendLine($"        memcpy(p, {paramName}_raw, {paramName}_len * 2); p += {paramName}_len * 2;");
            return;
        }

        if (typeName is "Guid")
        {
            sb.AppendLine($"        memcpy(p, &{paramName}, 16); p += 16;");
            return;
        }

        if (type.ResolvedSymbol is EnumSymbol)
        {
            sb.AppendLine($"        INT32 {paramName}_val = static_cast<INT32>({paramName});");
            sb.AppendLine($"        memcpy(p, &{paramName}_val, 4); p += 4;");
            return;
        }

        if (type.ResolvedSymbol is StructSymbol structSym)
        {
            EmitSerializeStruct(sb, paramName, structSym);
            return;
        }

        // Primitive types
        var size = GetPrimitiveSize(typeName);
        if (size > 0)
        {
            sb.AppendLine($"        memcpy(p, &{paramName}, {size}); p += {size};");
            return;
        }

        // EventRegistrationToken
        if (typeName is "EventRegistrationToken")
        {
            sb.AppendLine($"        memcpy(p, &{paramName}, 8); p += 8;");
            return;
        }

        // Fallback for interface pointers etc.
        sb.AppendLine($"        // TODO: marshal {paramName} of type {typeName}");
    }

    private static void EmitSerializeStruct(StringBuilder sb, string paramName, StructSymbol structSym)
    {
        foreach (var field in structSym.Fields)
        {
            var fieldAccess = $"{paramName}.{field.Name}";
            EmitSerialize(sb, fieldAccess, field.Type);
        }
    }

    /// <summary>
    /// Emits C++ code to deserialize a value from the RPC reply buffer.
    /// Assumes a BYTE* pReply variable is in scope and advances it.
    /// </summary>
    internal static void EmitDeserialize(StringBuilder sb, string targetName, TypeRef type, bool isPointer)
    {
        var typeName = type.Name;
        var deref = isPointer ? $"*{targetName}" : targetName;

        if (typeName is "String")
        {
            // HSTRING deserialization
            sb.AppendLine($"        UINT32 {targetName}_len; memcpy(&{targetName}_len, pReply, 4); pReply += 4;");
            sb.AppendLine($"        WindowsCreateString((PCWSTR)pReply, {targetName}_len, {(isPointer ? targetName : $"&{targetName}")}); pReply += {targetName}_len * 2;");
            return;
        }

        if (typeName is "Guid")
        {
            sb.AppendLine($"        memcpy({(isPointer ? targetName : $"&{targetName}")}, pReply, 16); pReply += 16;");
            return;
        }

        if (type.ResolvedSymbol is EnumSymbol)
        {
            sb.AppendLine($"        INT32 {targetName}_val; memcpy(&{targetName}_val, pReply, 4); pReply += 4;");
            sb.AppendLine($"        {deref} = static_cast<decltype({deref})>({targetName}_val);");
            return;
        }

        if (type.ResolvedSymbol is StructSymbol structSym)
        {
            EmitDeserializeStruct(sb, targetName, structSym, isPointer);
            return;
        }

        var size = GetPrimitiveSize(typeName);
        if (size > 0)
        {
            sb.AppendLine($"        memcpy({(isPointer ? targetName : $"&{targetName}")}, pReply, {size}); pReply += {size};");
            return;
        }

        if (typeName is "EventRegistrationToken")
        {
            sb.AppendLine($"        memcpy({(isPointer ? targetName : $"&{targetName}")}, pReply, 8); pReply += 8;");
            return;
        }

        sb.AppendLine($"        // TODO: unmarshal {targetName} of type {typeName}");
    }

    private static void EmitDeserializeStruct(StringBuilder sb, string targetName, StructSymbol structSym, bool isPointer)
    {
        var prefix = isPointer ? $"{targetName}->" : $"{targetName}.";
        foreach (var field in structSym.Fields)
        {
            var fieldTarget = $"{prefix}{field.Name}";
            EmitDeserialize(sb, fieldTarget, field.Type, isPointer: false);
        }
    }

    /// <summary>
    /// Returns the byte size for a primitive type name, or 0 if not a recognized primitive.
    /// </summary>
    internal static int GetPrimitiveSize(string typeName)
    {
        return typeName switch
        {
            "Boolean" or "UInt8" => 1,
            "Int16" or "UInt16" or "Char" => 2,
            "Int32" or "UInt32" or "Single" or "HRESULT" => 4,
            "Int64" or "UInt64" or "Double" => 8,
            _ => 0,
        };
    }

    /// <summary>
    /// Computes the vtable slot for a specific method within an interface.
    /// IUnknown: 0-2, IInspectable: 3-5, user methods: 6+
    /// </summary>
    internal static int ComputeVtableSlot(InterfaceSymbol iface, string methodName)
    {
        var methods = CollectInterfaceMethods(iface);
        int slot = UserMethodStartSlot;
        foreach (var m in methods)
        {
            if (m.Name == methodName)
                return slot;
            slot++;
        }
        return -1; // not found
    }
}

/// <summary>
/// Represents a parameter in the proxy method, with direction information.
/// </summary>
public record ProxyParam(string Name, TypeRef Type, ParamDirection Direction);

/// <summary>
/// Parameter direction for proxy serialization.
/// </summary>
public enum ParamDirection
{
    In,
    Out
}

/// <summary>
/// Categorizes what kind of interface member generated this method.
/// </summary>
public enum MemberKind
{
    Method,
    PropertyGetter,
    PropertySetter,
    EventAdd,
    EventRemove
}
