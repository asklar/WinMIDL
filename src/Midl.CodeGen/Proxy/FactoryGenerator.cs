using System.Security.Cryptography;
using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;
using Midl.CodeGen.Header;

namespace Midl.CodeGen.Proxy;

/// <summary>
/// Generates CPSFactory (IPSFactoryBuffer) class and DLL export plumbing
/// for custom proxy/stub DLLs. This is the glue code COM uses to discover
/// and load the proxy/stub implementations produced by ProxyGenerator and StubGenerator.
/// </summary>
public class FactoryGenerator
{
    /// <summary>
    /// Generate the factory C++ code for all non-external interfaces and delegates.
    /// Delegates are COM interfaces at the ABI level (IUnknown + Invoke) and need
    /// proxy/stub registration so they can be marshaled across apartments.
    /// </summary>
    public string Generate(Compilation compilation)
    {
        var sb = new StringBuilder();

        var allTypes = compilation.GetAllTypes().Where(t => !t.IsExternal).ToList();

        var interfaces = allTypes.OfType<InterfaceSymbol>().ToList();
        var delegates = allTypes.OfType<DelegateSymbol>().ToList();

        EmitPrologue(sb);

        if (interfaces.Count == 0 && delegates.Count == 0)
            return sb.ToString();

        var clsid = ComputeClsid(interfaces, delegates);
        EmitClsidDefinition(sb, clsid);

        EmitFactoryClass(sb, interfaces, delegates);
        EmitGlobalInstance(sb);
        EmitDllGetClassObject(sb);
        EmitDllCanUnloadNow(sb);
        EmitDllRegisterServer(sb, interfaces, delegates);
        EmitDllUnregisterServer(sb, interfaces, delegates);

        return sb.ToString();
    }

    /// <summary>
    /// Generate a .def file for the DLL exports.
    /// </summary>
    public string GenerateDefFile(Compilation compilation, string libraryName)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"LIBRARY {libraryName}");
        sb.AppendLine("EXPORTS");
        sb.AppendLine("    DllGetClassObject   PRIVATE");
        sb.AppendLine("    DllCanUnloadNow     PRIVATE");
        sb.AppendLine("    DllRegisterServer   PRIVATE");
        sb.AppendLine("    DllUnregisterServer PRIVATE");
        return sb.ToString();
    }

    /// <summary>
    /// Compute a deterministic CLSID for the proxy/stub factory using UUID v5
    /// (SHA-1 based) from the sorted list of interface and delegate full names.
    /// </summary>
    internal static Guid ComputeClsid(IReadOnlyList<InterfaceSymbol> interfaces, IReadOnlyList<DelegateSymbol>? delegates = null)
    {
        // Use a fixed namespace UUID for MIDL proxy/stub CLSIDs
        var namespaceId = new Guid("6ba7b810-9dad-11d1-80b4-00c04fd430c8"); // DNS namespace from RFC 4122

        var sortedNames = interfaces
            .Select(i => i.FullName)
            .Concat((delegates ?? []).Select(d => d.FullName))
            .OrderBy(n => n, StringComparer.Ordinal)
            .ToList();

        var combined = string.Join("|", sortedNames);
        return GenerateUuidV5(namespaceId, combined);
    }

    private static Guid GenerateUuidV5(Guid namespaceId, string name)
    {
        var namespaceBytes = namespaceId.ToByteArray();
        // Convert to network byte order for RFC 4122 compliance
        SwapGuidBytes(namespaceBytes);

        var nameBytes = Encoding.UTF8.GetBytes(name);

        byte[] hash;
        using (var sha1 = SHA1.Create())
        {
            sha1.TransformBlock(namespaceBytes, 0, namespaceBytes.Length, null, 0);
            sha1.TransformFinalBlock(nameBytes, 0, nameBytes.Length);
            hash = sha1.Hash!;
        }

        // Set version 5 (SHA-1) and variant bits per RFC 4122
        hash[6] = (byte)((hash[6] & 0x0F) | 0x50); // version 5
        hash[8] = (byte)((hash[8] & 0x3F) | 0x80); // variant 10xx

        var result = new byte[16];
        Array.Copy(hash, 0, result, 0, 16);

        // Convert back from network byte order
        SwapGuidBytes(result);
        return new Guid(result);
    }

    private static void SwapGuidBytes(byte[] bytes)
    {
        // Swap Data1 (4 bytes)
        (bytes[0], bytes[3]) = (bytes[3], bytes[0]);
        (bytes[1], bytes[2]) = (bytes[2], bytes[1]);
        // Swap Data2 (2 bytes)
        (bytes[4], bytes[5]) = (bytes[5], bytes[4]);
        // Swap Data3 (2 bytes)
        (bytes[6], bytes[7]) = (bytes[7], bytes[6]);
    }

    private static void EmitPrologue(StringBuilder sb)
    {
        sb.AppendLine("// Factory and DLL exports auto-generated by MIDL compiler");
        sb.AppendLine("// Provides IPSFactoryBuffer implementation for custom proxy/stub DLL");
        sb.AppendLine();
        WireFormat.EmitConsolidatedIncludes(sb);
    }

    private static void EmitClsidDefinition(StringBuilder sb, Guid clsid)
    {
        sb.AppendLine($"static const CLSID CLSID_PSFactoryBuffer = {FormatGuidInitializer(clsid)};");
        sb.AppendLine();
    }

    private static string FormatGuidInitializer(Guid guid)
    {
        var bytes = guid.ToByteArray();
        var a = BitConverter.ToUInt32(bytes, 0);
        var b = BitConverter.ToUInt16(bytes, 4);
        var c = BitConverter.ToUInt16(bytes, 6);
        var d = bytes[8..16];

        return $"{{ 0x{a:x8}, 0x{b:x4}, 0x{c:x4}, {{ {string.Join(", ", d.Select(x => $"0x{x:x2}"))} }} }}";
    }

    private static string GetProxyClassName(InterfaceSymbol iface) => $"C{iface.Name}Proxy";
    private static string GetProxyClassName(DelegateSymbol del) => $"C{del.Name}Proxy";

    private static string GetStubClassName(InterfaceSymbol iface) =>
        $"CStub_{HeaderEmitter.MangleName(iface.FullName)}";
    private static string GetStubClassName(DelegateSymbol del) =>
        $"CStub_{HeaderEmitter.MangleName(del.FullName)}";

    private static string GetIidName(InterfaceSymbol iface) =>
        $"IID_{HeaderEmitter.MangleName(iface.FullName)}";
    private static string GetIidName(DelegateSymbol del) =>
        $"IID_{HeaderEmitter.MangleName(del.FullName)}";

    private static void EmitFactoryClass(StringBuilder sb, List<InterfaceSymbol> interfaces, List<DelegateSymbol> delegates)
    {
        sb.AppendLine("class CPSFactory : public IPSFactoryBuffer {");
        sb.AppendLine("    LONG m_cRef;");
        sb.AppendLine();
        sb.AppendLine("public:");
        sb.AppendLine("    CPSFactory() : m_cRef(1) {}");
        sb.AppendLine();

        EmitQueryInterface(sb);
        EmitAddRefRelease(sb);
        EmitCreateProxy(sb, interfaces, delegates);
        EmitCreateStub(sb, interfaces, delegates);

        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitQueryInterface(StringBuilder sb)
    {
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE QueryInterface(REFIID riid, void** ppv) override {");
        sb.AppendLine("        if (riid == IID_IUnknown || riid == IID_IPSFactoryBuffer)");
        sb.AppendLine("            { *ppv = this; AddRef(); return S_OK; }");
        sb.AppendLine("        *ppv = nullptr; return E_NOINTERFACE;");
        sb.AppendLine("    }");
    }

    private static void EmitAddRefRelease(StringBuilder sb)
    {
        sb.AppendLine("    ULONG STDMETHODCALLTYPE AddRef() override { return InterlockedIncrement(&m_cRef); }");
        sb.AppendLine("    ULONG STDMETHODCALLTYPE Release() override {");
        sb.AppendLine("        ULONG c = InterlockedDecrement(&m_cRef);");
        sb.AppendLine("        if (c == 0) delete this;");
        sb.AppendLine("        return c;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitCreateProxy(StringBuilder sb, List<InterfaceSymbol> interfaces, List<DelegateSymbol> delegates)
    {
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE CreateProxy(");
        sb.AppendLine("        IUnknown* pUnkOuter, REFIID riid,");
        sb.AppendLine("        IRpcProxyBuffer** ppProxy, void** ppv) override");
        sb.AppendLine("    {");

        foreach (var iface in interfaces)
        {
            var iidName = GetIidName(iface);
            var proxyClass = GetProxyClassName(iface);

            sb.AppendLine($"        if (riid == {iidName}) {{");
            sb.AppendLine($"            auto* proxy = new {proxyClass}(pUnkOuter);");
            sb.AppendLine("            *ppProxy = proxy;");
            sb.AppendLine("            *ppv = proxy->GetFace();");
            sb.AppendLine("            pUnkOuter->AddRef();");
            sb.AppendLine("            return S_OK;");
            sb.AppendLine("        }");
        }

        foreach (var del in delegates)
        {
            var iidName = GetIidName(del);
            var proxyClass = GetProxyClassName(del);

            sb.AppendLine($"        if (riid == {iidName}) {{");
            sb.AppendLine($"            auto* proxy = new {proxyClass}(pUnkOuter);");
            sb.AppendLine("            *ppProxy = proxy;");
            sb.AppendLine("            *ppv = proxy->GetFace();");
            sb.AppendLine("            pUnkOuter->AddRef();");
            sb.AppendLine("            return S_OK;");
            sb.AppendLine("        }");
        }

        sb.AppendLine("        return E_NOINTERFACE;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitCreateStub(StringBuilder sb, List<InterfaceSymbol> interfaces, List<DelegateSymbol> delegates)
    {
        sb.AppendLine("    HRESULT STDMETHODCALLTYPE CreateStub(");
        sb.AppendLine("        REFIID riid, IUnknown* pServer,");
        sb.AppendLine("        IRpcStubBuffer** ppStub) override");
        sb.AppendLine("    {");

        foreach (var iface in interfaces)
        {
            var iidName = GetIidName(iface);
            var stubClass = GetStubClassName(iface);

            sb.AppendLine($"        if (riid == {iidName}) {{");
            sb.AppendLine($"            auto* stub = new {stubClass}();");
            sb.AppendLine("            if (pServer) stub->Connect(pServer);");
            sb.AppendLine("            *ppStub = stub;");
            sb.AppendLine("            return S_OK;");
            sb.AppendLine("        }");
        }

        foreach (var del in delegates)
        {
            var iidName = GetIidName(del);
            var stubClass = GetStubClassName(del);

            sb.AppendLine($"        if (riid == {iidName}) {{");
            sb.AppendLine($"            auto* stub = new {stubClass}();");
            sb.AppendLine("            if (pServer) stub->Connect(pServer);");
            sb.AppendLine("            *ppStub = stub;");
            sb.AppendLine("            return S_OK;");
            sb.AppendLine("        }");
        }

        sb.AppendLine("        return E_NOINTERFACE;");
        sb.AppendLine("    }");
    }

    private static void EmitGlobalInstance(StringBuilder sb)
    {
        sb.AppendLine("static CPSFactory g_PSFactory;");
        sb.AppendLine();
    }

    private static void EmitDllGetClassObject(StringBuilder sb)
    {
        sb.AppendLine("HRESULT STDAPICALLTYPE DllGetClassObject(REFCLSID rclsid, REFIID riid, void** ppv) {");
        sb.AppendLine("    if (rclsid == CLSID_PSFactoryBuffer)");
        sb.AppendLine("        return g_PSFactory.QueryInterface(riid, ppv);");
        sb.AppendLine("    return CLASS_E_CLASSNOTAVAILABLE;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitDllCanUnloadNow(StringBuilder sb)
    {
        sb.AppendLine("HRESULT STDAPICALLTYPE DllCanUnloadNow() { return S_FALSE; /* always stay loaded */ }");
        sb.AppendLine();
    }

    private static void EmitDllRegisterServer(StringBuilder sb, List<InterfaceSymbol> interfaces, List<DelegateSymbol> delegates)
    {
        sb.AppendLine("HRESULT STDAPICALLTYPE DllRegisterServer() {");
        sb.AppendLine("    HMODULE hMod;");
        sb.AppendLine("    GetModuleHandleExW(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS, (LPCWSTR)&g_PSFactory, &hMod);");
        sb.AppendLine("    WCHAR dllPath[MAX_PATH];");
        sb.AppendLine("    GetModuleFileNameW(hMod, dllPath, MAX_PATH);");
        sb.AppendLine();
        sb.AppendLine("    WCHAR clsidStr[64];");
        sb.AppendLine("    StringFromGUID2(CLSID_PSFactoryBuffer, clsidStr, 64);");
        sb.AppendLine();

        // Register CLSID → InprocServer32
        sb.AppendLine("    // Register CLSID_PSFactoryBuffer InprocServer32");
        sb.AppendLine("    {");
        sb.AppendLine("        WCHAR keyPath[256];");
        sb.AppendLine("        wsprintfW(keyPath, L\"Software\\\\Classes\\\\CLSID\\\\%s\\\\InprocServer32\", clsidStr);");
        sb.AppendLine("        HKEY hKey;");
        sb.AppendLine("        RegCreateKeyExW(HKEY_LOCAL_MACHINE, keyPath, 0, nullptr, 0, KEY_SET_VALUE, nullptr, &hKey, nullptr);");
        sb.AppendLine("        RegSetValueExW(hKey, nullptr, 0, REG_SZ, (BYTE*)dllPath, (DWORD)(wcslen(dllPath) + 1) * sizeof(WCHAR));");
        sb.AppendLine("        RegCloseKey(hKey);");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Register each interface IID → ProxyStubClsid32
        foreach (var iface in interfaces)
        {
            var iidName = GetIidName(iface);
            sb.AppendLine($"    // Register {iidName} -> ProxyStubClsid32");
            sb.AppendLine("    {");
            sb.AppendLine("        WCHAR iidStr[64];");
            sb.AppendLine($"        StringFromGUID2({iidName}, iidStr, 64);");
            sb.AppendLine("        WCHAR keyPath[256];");
            sb.AppendLine("        wsprintfW(keyPath, L\"Software\\\\Classes\\\\Interface\\\\%s\\\\ProxyStubClsid32\", iidStr);");
            sb.AppendLine("        HKEY hKey;");
            sb.AppendLine("        RegCreateKeyExW(HKEY_LOCAL_MACHINE, keyPath, 0, nullptr, 0, KEY_SET_VALUE, nullptr, &hKey, nullptr);");
            sb.AppendLine("        RegSetValueExW(hKey, nullptr, 0, REG_SZ, (BYTE*)clsidStr, (DWORD)(wcslen(clsidStr) + 1) * sizeof(WCHAR));");
            sb.AppendLine("        RegCloseKey(hKey);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Register each delegate IID → ProxyStubClsid32
        foreach (var del in delegates)
        {
            var iidName = GetIidName(del);
            sb.AppendLine($"    // Register {iidName} -> ProxyStubClsid32");
            sb.AppendLine("    {");
            sb.AppendLine("        WCHAR iidStr[64];");
            sb.AppendLine($"        StringFromGUID2({iidName}, iidStr, 64);");
            sb.AppendLine("        WCHAR keyPath[256];");
            sb.AppendLine("        wsprintfW(keyPath, L\"Software\\\\Classes\\\\Interface\\\\%s\\\\ProxyStubClsid32\", iidStr);");
            sb.AppendLine("        HKEY hKey;");
            sb.AppendLine("        RegCreateKeyExW(HKEY_LOCAL_MACHINE, keyPath, 0, nullptr, 0, KEY_SET_VALUE, nullptr, &hKey, nullptr);");
            sb.AppendLine("        RegSetValueExW(hKey, nullptr, 0, REG_SZ, (BYTE*)clsidStr, (DWORD)(wcslen(clsidStr) + 1) * sizeof(WCHAR));");
            sb.AppendLine("        RegCloseKey(hKey);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("    return S_OK;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitDllUnregisterServer(StringBuilder sb, List<InterfaceSymbol> interfaces, List<DelegateSymbol> delegates)
    {
        sb.AppendLine("HRESULT STDAPICALLTYPE DllUnregisterServer() {");
        sb.AppendLine("    WCHAR clsidStr[64];");
        sb.AppendLine("    StringFromGUID2(CLSID_PSFactoryBuffer, clsidStr, 64);");
        sb.AppendLine();

        // Remove CLSID
        sb.AppendLine("    // Remove CLSID_PSFactoryBuffer");
        sb.AppendLine("    {");
        sb.AppendLine("        WCHAR keyPath[256];");
        sb.AppendLine("        wsprintfW(keyPath, L\"Software\\\\Classes\\\\CLSID\\\\%s\", clsidStr);");
        sb.AppendLine("        RegDeleteKeyW(HKEY_LOCAL_MACHINE, keyPath);");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Remove each interface IID
        foreach (var iface in interfaces)
        {
            var iidName = GetIidName(iface);
            sb.AppendLine($"    // Remove {iidName}");
            sb.AppendLine("    {");
            sb.AppendLine("        WCHAR iidStr[64];");
            sb.AppendLine($"        StringFromGUID2({iidName}, iidStr, 64);");
            sb.AppendLine("        WCHAR keyPath[256];");
            sb.AppendLine("        wsprintfW(keyPath, L\"Software\\\\Classes\\\\Interface\\\\%s\\\\ProxyStubClsid32\", iidStr);");
            sb.AppendLine("        RegDeleteKeyW(HKEY_LOCAL_MACHINE, keyPath);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Remove each delegate IID
        foreach (var del in delegates)
        {
            var iidName = GetIidName(del);
            sb.AppendLine($"    // Remove {iidName}");
            sb.AppendLine("    {");
            sb.AppendLine("        WCHAR iidStr[64];");
            sb.AppendLine($"        StringFromGUID2({iidName}, iidStr, 64);");
            sb.AppendLine("        WCHAR keyPath[256];");
            sb.AppendLine("        wsprintfW(keyPath, L\"Software\\\\Classes\\\\Interface\\\\%s\\\\ProxyStubClsid32\", iidStr);");
            sb.AppendLine("        RegDeleteKeyW(HKEY_LOCAL_MACHINE, keyPath);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("    return S_OK;");
        sb.AppendLine("}");
    }
}
