using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;
using Midl.CodeGen.Header;

namespace Midl.CodeGen.Iid;

/// <summary>
/// Generates _i.c files containing IID and CLSID definitions for interfaces and coclasses.
/// </summary>
public class IidEmitter
{
    public string Emit(Compilation compilation)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// IID definitions");
        sb.AppendLine("//");
        sb.AppendLine("// This file is auto-generated by the MIDL compiler.");
        sb.AppendLine();
        sb.AppendLine("#ifdef _MIDL_USE_GUIDDEF_");
        sb.AppendLine();
        sb.AppendLine("#ifndef INITGUID");
        sb.AppendLine("#define INITGUID");
        sb.AppendLine("#include <guiddef.h>");
        sb.AppendLine("#undef INITGUID");
        sb.AppendLine("#else");
        sb.AppendLine("#include <guiddef.h>");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("#define MIDL_DEFINE_GUID(type,name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8) \\");
        sb.AppendLine("        DEFINE_GUID(name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8)");
        sb.AppendLine();
        sb.AppendLine("#else");
        sb.AppendLine();
        sb.AppendLine("#include <rpc.h>");
        sb.AppendLine("#include <rpcndr.h>");
        sb.AppendLine();
        sb.AppendLine("#define MIDL_DEFINE_GUID(type,name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8) \\");
        sb.AppendLine("    EXTERN_C const type name = {l,w1,w2,{b1,b2,b3,b4,b5,b6,b7,b8}}");
        sb.AppendLine();
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("#ifdef __cplusplus");
        sb.AppendLine("extern \"C\" {");
        sb.AppendLine("#endif");

        bool emittedAny = false;
        foreach (var symbol in compilation.GetAllTypes().Where(t => !t.IsExternal))
        {
            if (symbol is InterfaceSymbol iface)
            {
                var guid = iface.Uuid ?? AbiGuidComputer.ComputeGuid(iface);
                var mangledName = HeaderEmitter.MangleName(iface.FullName);
                sb.AppendLine();
                EmitGuidConstant(sb, "IID", $"IID_{mangledName}", guid);
                emittedAny = true;
            }
            else if (symbol is DelegateSymbol d)
            {
                var guid = d.Uuid ?? AbiGuidComputer.ComputeGuid(d);
                var mangledName = HeaderEmitter.MangleName(d.FullName);
                sb.AppendLine();
                EmitGuidConstant(sb, "IID", $"IID_{mangledName}", guid);
                emittedAny = true;
            }
            else if (symbol is RuntimeClassSymbol rc && rc.Uuid.HasValue)
            {
                sb.AppendLine();
                EmitGuidConstant(sb, "CLSID", $"CLSID_{rc.Name}", rc.Uuid.Value);
                emittedAny = true;
            }
        }

        if (!emittedAny)
        {
            sb.AppendLine();
        }

        sb.AppendLine();
        sb.AppendLine("#ifdef __cplusplus");
        sb.AppendLine("}");
        sb.AppendLine("#endif");

        return sb.ToString();
    }

    public void EmitToFile(Compilation compilation, string outputPath)
    {
        var content = Emit(compilation);
        File.WriteAllText(outputPath, content);
    }

    private static void EmitGuidConstant(StringBuilder sb, string type, string name, Guid guid)
    {
        var bytes = guid.ToByteArray();
        // Guid.ToByteArray() layout: a(4) b(2) c(2) d(8)
        uint a = BitConverter.ToUInt32(bytes, 0);
        ushort b = BitConverter.ToUInt16(bytes, 4);
        ushort c = BitConverter.ToUInt16(bytes, 6);

        sb.AppendLine($"// {{{guid.ToString("D").ToUpperInvariant()}}}");
        sb.Append($"MIDL_DEFINE_GUID({type},{name},0x{a:X8},0x{b:X4},0x{c:X4},");
        sb.Append($"0x{bytes[8]:X2},0x{bytes[9]:X2},");
        sb.Append($"0x{bytes[10]:X2},0x{bytes[11]:X2},");
        sb.Append($"0x{bytes[12]:X2},0x{bytes[13]:X2},");
        sb.Append($"0x{bytes[14]:X2},0x{bytes[15]:X2}");
        sb.AppendLine(");");
    }
}
