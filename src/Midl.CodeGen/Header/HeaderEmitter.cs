using System.Security.Cryptography;
using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;
using static Midl.Analysis.AbiGuidComputer;
using Midl.Syntax;

namespace Midl.CodeGen.Header;

/// <summary>
/// Generates C/C++ header files from a MIDL compilation's symbol table.
/// </summary>
public partial class HeaderEmitter
{
    private static readonly Dictionary<string, string> TypeMap = new(StringComparer.Ordinal)
    {
        ["Int16"] = "short",
        ["Int32"] = "int",
        ["Int64"] = "__int64",
        ["UInt8"] = "::byte",
        ["UInt16"] = "unsigned short",
        ["UInt32"] = "unsigned int",
        ["UInt64"] = "unsigned __int64",
        ["Single"] = "float",
        ["Double"] = "double",
        ["Boolean"] = "::boolean",
        ["Char"] = "wchar_t",
        ["String"] = "HSTRING",
        ["Guid"] = "GUID",
        ["Object"] = "IInspectable*",
        ["void"] = "void",
        ["HRESULT"] = "HRESULT",
    };

    public string Emit(Compilation compilation) => Emit(compilation, inputFilename: null);

    public string Emit(Compilation compilation, string? inputFilename)
    {
        var sb = new StringBuilder();
        var baseGuard = BuildBaseGuardName(compilation);
        var outerGuard = $"__{baseGuard}_h__";
        var innerGuard = $"__{baseGuard}_p_h__";

        EmitBoilerplateHeader(sb, baseGuard, outerGuard, innerGuard, inputFilename);

        // Collect all types (exclude imported/external types)
        var allTypes = compilation.GetAllTypes().Where(t => !t.IsExternal).ToList();
        MidlTrace.CodeGen($"Generating header, {allTypes.Count} types");

        // C-section types: runtime classes, enums, structs
        foreach (var symbol in allTypes)
        {
            switch (symbol)
            {
                case RuntimeClassSymbol rc:
                    EmitRuntimeClassWithComment(sb, rc);
                    break;
                case EnumSymbol e:
                    EmitEnum(sb, e);
                    break;
                case StructSymbol s:
                    EmitStruct(sb, s);
                    break;
            }
        }

        // Collect C++ types (interfaces and delegates)
        var cppTypes = allTypes.Where(t => t is InterfaceSymbol or DelegateSymbol).ToList();
        var hasForwardDecls = allTypes.Any(t => t is InterfaceSymbol or RuntimeClassSymbol);

        if (cppTypes.Count > 0)
        {
            // Emit IID declarations in C section (before C++ guard)
            foreach (var symbol in cppTypes)
            {
                var mangledName = MangleName(symbol.FullName);
                sb.AppendLine($"EXTERN_C const IID IID_{mangledName};");
            }
            sb.AppendLine();
        }

        if (cppTypes.Count > 0 || hasForwardDecls)
        {
            sb.AppendLine("#if defined(__cplusplus) && !defined(CINTERFACE)");
            sb.AppendLine();

            // Forward declarations (with FWD_DEFINED guards and namespace blocks)
            EmitForwardDeclarations(sb, allTypes);

            foreach (var symbol in cppTypes)
            {
                switch (symbol)
                {
                    case DelegateSymbol d:
                        EmitDelegateCpp(sb, d);
                        break;
                    case InterfaceSymbol iface:
                        EmitInterfaceCpp(sb, iface);
                        break;
                }
            }

            sb.AppendLine("#endif // defined(__cplusplus) && !defined(CINTERFACE)");
            sb.AppendLine();
        }

        EmitBoilerplateFooter(sb, innerGuard, outerGuard);

        return sb.ToString();
    }

    public void EmitToFile(Compilation compilation, string outputPath)
    {
        var content = Emit(compilation);
        File.WriteAllText(outputPath, content, Encoding.UTF8);
    }

    private static void EmitBoilerplateHeader(StringBuilder sb, string baseGuard, string outerGuard, string innerGuard, string? inputFilename)
    {
        // Banner comment
        if (!string.IsNullOrEmpty(inputFilename))
            sb.AppendLine($"/* Header file automatically generated from {inputFilename} */");
        else
            sb.AppendLine("/* Header file automatically generated by WinMIDL compiler */");

        sb.AppendLine("/*");
        sb.AppendLine(" * File built with WinMIDL Compiler");
        sb.AppendLine(" */");

        // Warning suppression
        sb.AppendLine("#pragma warning( disable: 4049 )  /* more than 64k source lines */");

        // RPC version requirements
        sb.AppendLine("/* verify that the <rpcndr.h> version is high enough to compile this file*/");
        sb.AppendLine("#ifndef __REQUIRED_RPCNDR_H_VERSION__");
        sb.AppendLine("#define __REQUIRED_RPCNDR_H_VERSION__ 500");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("/* verify that the <rpcsal.h> version is high enough to compile this file*/");
        sb.AppendLine("#ifndef __REQUIRED_RPCSAL_H_VERSION__");
        sb.AppendLine("#define __REQUIRED_RPCSAL_H_VERSION__ 100");
        sb.AppendLine("#endif");
        sb.AppendLine();

        // RPC includes
        sb.AppendLine("#include <rpc.h>");
        sb.AppendLine("#include <rpcndr.h>");
        sb.AppendLine();

        // RPCNDR version check
        sb.AppendLine("#ifndef __RPCNDR_H_VERSION__");
        sb.AppendLine("#error this stub requires an updated version of <rpcndr.h>");
        sb.AppendLine("#endif /* __RPCNDR_H_VERSION__ */");
        sb.AppendLine();

        // COM/Windows includes
        sb.AppendLine("#ifndef COM_NO_WINDOWS_H");
        sb.AppendLine("#include <windows.h>");
        sb.AppendLine("#include <ole2.h>");
        sb.AppendLine("#endif /*COM_NO_WINDOWS_H*/");
        sb.AppendLine();

        // Double include guard
        sb.AppendLine($"#ifndef {outerGuard}");
        sb.AppendLine($"#define {outerGuard}");
        sb.AppendLine($"#ifndef {innerGuard}");
        sb.AppendLine($"#define {innerGuard}");
        sb.AppendLine();
        sb.AppendLine("#pragma once");
        sb.AppendLine();

        // NS prefix check
        sb.AppendLine("// Ensure that the setting of the /ns_prefix command line switch is consistent for all headers.");
        sb.AppendLine("// If you get an error from the compiler indicating \"warning C4005: 'CHECK_NS_PREFIX_STATE': macro redefinition\", this");
        sb.AppendLine("// indicates that you have included two different headers with different settings for the /ns_prefix MIDL command line switch");
        sb.AppendLine("#if !defined(DISABLE_NS_PREFIX_CHECKS)");
        sb.AppendLine("#define CHECK_NS_PREFIX_STATE \"never\"");
        sb.AppendLine("#endif // !defined(DISABLE_NS_PREFIX_CHECKS)");
        sb.AppendLine();

        // MIDL_CONST_ID macro
        sb.AppendLine("#pragma push_macro(\"MIDL_CONST_ID\")");
        sb.AppendLine("#undef MIDL_CONST_ID");
        sb.AppendLine("#define MIDL_CONST_ID const __declspec(selectany)");
        sb.AppendLine();

        // Header files for imported files
        sb.AppendLine("// Header files for imported files");
        sb.AppendLine("#include \"winrtbase.h\"");
        sb.AppendLine();
    }

    private static void EmitBoilerplateFooter(StringBuilder sb, string innerGuard, string outerGuard)
    {
        sb.AppendLine($"#pragma pop_macro(\"MIDL_CONST_ID\")");
        sb.AppendLine();
        sb.AppendLine($"#endif // {innerGuard}");
        sb.AppendLine();
        sb.AppendLine($"#endif // {outerGuard}");
    }

    private static string BuildBaseGuardName(Compilation compilation)
    {
        // Use the first namespace found, or a generic name
        var allTypes = compilation.GetAllTypes().Where(t => !t.IsExternal).ToList();
        string nsName = "";
        foreach (var t in allTypes)
        {
            if (t.ContainingSymbol is NamespaceSymbol ns && ns.FullName.Length > 0)
            {
                nsName = ns.FullName;
                break;
            }
        }

        if (string.IsNullOrEmpty(nsName))
            nsName = "Generated";

        return nsName.Replace(".", "_");
    }

    private static void EmitForwardDeclarations(StringBuilder sb, List<ISymbol> allTypes)
    {
        var interfaces = allTypes.OfType<InterfaceSymbol>().ToList();
        var runtimeClasses = allTypes.OfType<RuntimeClassSymbol>().ToList();

        if (interfaces.Count == 0 && runtimeClasses.Count == 0)
            return;

        sb.AppendLine("/* Forward Declarations */");

        foreach (var iface in interfaces)
        {
            var mangledName = MangleName(iface.FullName);
            var fwdGuard = $"__{mangledName}_FWD_DEFINED__";

            sb.AppendLine($"#ifndef {fwdGuard}");
            sb.AppendLine($"#define {fwdGuard}");
            sb.AppendLine();
            EmitNamespaceBlock(sb, iface.FullName, "interface");
            sb.AppendLine($"#define {mangledName} {iface.FullName.Replace(".", "::")}");
            sb.AppendLine();
            sb.AppendLine($"#endif // {fwdGuard}");
            sb.AppendLine();
        }

        foreach (var rc in runtimeClasses)
        {
            EmitNamespaceBlock(sb, rc.FullName, "class");
            sb.AppendLine();
        }
    }

    /// <summary>
    /// Emits a type declaration wrapped in nested namespace blocks.
    /// </summary>
    private static void EmitNamespaceBlock(StringBuilder sb, string fullName, string keyword)
    {
        var lastDot = fullName.LastIndexOf('.');
        if (lastDot < 0)
        {
            sb.AppendLine($"{keyword} {fullName};");
            return;
        }

        var namespacePart = fullName[..lastDot];
        var typeName = fullName[(lastDot + 1)..];
        var segments = namespacePart.Split('.');

        for (int i = 0; i < segments.Length; i++)
        {
            var indent = new string(' ', i * 4);
            sb.AppendLine($"{indent}namespace {segments[i]} {{");
        }

        var typeIndent = new string(' ', segments.Length * 4);
        sb.AppendLine($"{typeIndent}{keyword} {typeName};");

        for (int i = segments.Length - 1; i >= 0; i--)
        {
            var indent = new string(' ', i * 4);
            sb.AppendLine($"{indent}}} /* {segments[i]} */");
        }
    }

    private static void EmitEnum(StringBuilder sb, EnumSymbol e)
    {
        sb.AppendLine($"enum {e.Name}");
        sb.AppendLine("{");
        for (int i = 0; i < e.EnumMembers.Count; i++)
        {
            var member = e.EnumMembers[i];
            var value = member.ExplicitValue ?? i;
            sb.AppendLine($"    {e.Name}_{member.Name} = {value},");
        }
        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitStruct(StringBuilder sb, StructSymbol s)
    {
        sb.AppendLine($"struct {s.Name}");
        sb.AppendLine("{");
        foreach (var field in s.Fields)
        {
            sb.AppendLine($"    {MapType(field.Type)} {field.Name};");
        }
        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitDelegateCpp(StringBuilder sb, DelegateSymbol d)
    {
        var mangledName = MangleName(d.FullName);
        var shortName = d.Name;
        var uuid = ComputeGuid(d).ToString("D");
        var nsParts = GetNamespaceParts(d);
        var nsIndent = new string(' ', nsParts.Length * 4);

        // Type comment (IID seed)
        var invokeMethod = new MethodSymbol("Invoke", null) { ReturnType = d.ReturnType };
        invokeMethod.Parameters.AddRange(d.Parameters);
        EmitTypeComment(sb, "Delegate", d.FullName, exclusiveToClass: null,
            hasExplicitUuid: d.Uuid.HasValue, new List<ISymbol> { invokeMethod });

        // Open namespace blocks
        for (int i = 0; i < nsParts.Length; i++)
        {
            var indent = new string(' ', i * 4);
            sb.AppendLine($"{indent}namespace {nsParts[i]} {{");
        }

        sb.AppendLine($"{nsIndent}MIDL_INTERFACE(\"{uuid}\")");
        sb.AppendLine($"{nsIndent}{shortName} : public IUnknown");
        sb.AppendLine($"{nsIndent}{{");
        sb.AppendLine($"{nsIndent}public:");

        // Delegate has an Invoke method
        var paramList = BuildParameterList(d.Parameters);
        var paramStr = paramList.Length > 0 ? paramList : "void";
        sb.AppendLine($"{nsIndent}    virtual HRESULT STDMETHODCALLTYPE Invoke({paramStr}) = 0;");

        sb.AppendLine($"{nsIndent}}};");

        // Close namespace blocks in reverse
        for (int i = nsParts.Length - 1; i >= 0; i--)
        {
            var indent = new string(' ', i * 4);
            sb.AppendLine($"{indent}}} /* {nsParts[i]} */");
        }
        sb.AppendLine();

        // Emit #define alias
        var qualifiedName = string.Join("::", nsParts.Append(shortName));
        sb.AppendLine($"#define {mangledName} {qualifiedName}");
        sb.AppendLine();
    }

    private static void EmitInterfaceCpp(StringBuilder sb, InterfaceSymbol iface)
    {
        var mangledName = MangleName(iface.FullName);
        var shortName = iface.Name;
        var uuid = ComputeGuid(iface).ToString("D");
        var guard = $"____{mangledName.TrimStart('_')}_INTERFACE_DEFINED__";
        var nsParts = GetNamespaceParts(iface);
        var nsIndent = new string(' ', nsParts.Length * 4);
        var dotName = iface.FullName;
        var underscoreName = dotName.Replace(".", "_");

        // Type comment (IID seed)
        EmitTypeComment(sb, "Interface", iface.FullName,
            GetExclusiveToClass(iface),
            hasExplicitUuid: iface.Uuid.HasValue, iface.Members.ToList());

        sb.AppendLine($"#ifndef {guard}");
        sb.AppendLine($"#define {guard}");
        sb.AppendLine();

        // InterfaceName string constant
        sb.AppendLine($"extern const __declspec(selectany) _Null_terminated_ WCHAR InterfaceName_{underscoreName}[] = L\"{dotName}\";");
        sb.AppendLine();

        // Open namespace blocks
        for (int i = 0; i < nsParts.Length; i++)
        {
            var indent = new string(' ', i * 4);
            sb.AppendLine($"{indent}namespace {nsParts[i]} {{");
        }

        sb.AppendLine($"{nsIndent}MIDL_INTERFACE(\"{uuid}\")");
        sb.AppendLine($"{nsIndent}{shortName} : public IInspectable");
        sb.AppendLine($"{nsIndent}{{");
        sb.AppendLine($"{nsIndent}public:");

        foreach (var member in iface.Members)
        {
            switch (member)
            {
                case PropertySymbol prop:
                    EmitPropertyMethods(sb, prop, nsIndent);
                    break;
                case MethodSymbol method:
                    EmitMethod(sb, method, nsIndent);
                    break;
                case EventSymbol evt:
                    EmitEventMethods(sb, evt, nsIndent);
                    break;
            }
        }

        sb.AppendLine($"{nsIndent}}};");

        // Close namespace blocks in reverse
        for (int i = nsParts.Length - 1; i >= 0; i--)
        {
            var indent = new string(' ', i * 4);
            sb.AppendLine($"{indent}}} /* {nsParts[i]} */");
        }
        sb.AppendLine();

        // Emit #define alias
        var qualifiedName = string.Join("::", nsParts.Append(shortName));
        sb.AppendLine($"#define {mangledName} {qualifiedName}");
        sb.AppendLine();
        sb.AppendLine($"#endif // {guard}");
        sb.AppendLine();
    }

    /// <summary>
    /// Gets the exclusive-to class name from either the symbol property (synthesized interfaces)
    /// or the [exclusiveto] attribute (explicitly declared interfaces).
    /// </summary>
    private static string? GetExclusiveToClass(InterfaceSymbol iface)
    {
        if (iface.ExclusiveToClass != null)
            return iface.ExclusiveToClass;

        var attr = iface.Attributes.FirstOrDefault(
            a => string.Equals(a.Name, "exclusiveto", StringComparison.OrdinalIgnoreCase));
        if (attr != null)
        {
            var className = attr.GetTypeName(0) ?? attr.GetIdentifier(0);
            if (className != null)
            {
                // Resolve to FQN if the class is in the same namespace
                if (!className.Contains('.') && iface.ContainingSymbol is NamespaceSymbol ns
                    && ns.FullName.Length > 0)
                {
                    return $"{ns.FullName}.{className}";
                }
                return className;
            }
        }

        return null;
    }

    private static void EmitTypeComment(StringBuilder sb, string kind, string fullName,
        string? exclusiveToClass, bool hasExplicitUuid, IReadOnlyList<ISymbol> members)
    {
        sb.AppendLine("/*");
        sb.AppendLine(" *");
        sb.AppendLine($" * {kind} {fullName}");
        sb.AppendLine(" *");

        if (exclusiveToClass != null)
        {
            sb.AppendLine($" * {kind} is a part of the implementation of type {exclusiveToClass}");
            sb.AppendLine(" *");
        }

        if (!hasExplicitUuid)
        {
            sb.AppendLine(" *");
            sb.AppendLine($" * The IID for this {kind.ToLowerInvariant()} was automatically generated by MIDLRT.");
            sb.AppendLine(" *");
            var seed = BuildAbiSignatureSeed(fullName, members);
            sb.AppendLine($" * {kind} IID generation seed: {seed}");
            sb.AppendLine(" *");
        }

        sb.AppendLine(" *");
        sb.AppendLine(" */");
    }

    private static void EmitPropertyMethods(StringBuilder sb, PropertySymbol prop, string nsIndent = "")
    {
        var cType = MapType(prop.Type);
        if (prop.HasGetter)
        {
            sb.AppendLine($"{nsIndent}    virtual HRESULT STDMETHODCALLTYPE get_{prop.Name}(/* [out, retval] */ {cType}* value) = 0;");
        }
        if (prop.HasSetter)
        {
            sb.AppendLine($"{nsIndent}    virtual HRESULT STDMETHODCALLTYPE put_{prop.Name}(/* [in] */ {cType} value) = 0;");
        }
    }

    private static void EmitMethod(StringBuilder sb, MethodSymbol method, string nsIndent = "")
    {
        var paramParts = new List<string>();
        foreach (var p in method.Parameters)
        {
            var cType = MapType(p.Type);
            if (p.Direction == ParameterDirection.Out)
                paramParts.Add($"/* [out] */ {cType}* {p.Name}");
            else if (p.Direction == ParameterDirection.RefConst)
                paramParts.Add($"/* [in] */ {cType}* {p.Name}");
            else
                paramParts.Add($"/* [in] */ {cType} {p.Name}");
        }

        // If non-void return, add retval out param
        if (method.ReturnType.Name != "void")
        {
            var retType = MapType(method.ReturnType);
            paramParts.Add($"/* [out, retval] */ {retType}* returnValue");
        }

        var paramStr = paramParts.Count > 0 ? string.Join(", ", paramParts) : "void";
        sb.AppendLine($"{nsIndent}    virtual HRESULT STDMETHODCALLTYPE {method.Name}({paramStr}) = 0;");
    }

    private static void EmitEventMethods(StringBuilder sb, EventSymbol evt, string nsIndent = "")
    {
        sb.AppendLine($"{nsIndent}    virtual HRESULT STDMETHODCALLTYPE add_{evt.Name}(/* [in] */ {MapType(evt.DelegateType)} handler, /* [out, retval] */ EventRegistrationToken* token) = 0;");
        sb.AppendLine($"{nsIndent}    virtual HRESULT STDMETHODCALLTYPE remove_{evt.Name}(/* [in] */ EventRegistrationToken token) = 0;");
    }

    private static void EmitRuntimeClass(StringBuilder sb, RuntimeClassSymbol rc)
    {
        var fullName = rc.FullName;
        var activationName = fullName.Replace(".", "_");
        sb.AppendLine($"extern const __declspec(selectany) _Null_terminated_ WCHAR RuntimeClass_{activationName}[] = L\"{fullName}\";");
        sb.AppendLine();
    }

    internal static string MapType(TypeRef typeRef)
    {
        if (typeRef.Name == "void")
            return "void";

        if (TypeMap.TryGetValue(typeRef.Name, out var mapped))
            return mapped;

        // For resolved user-defined types that are interfaces/delegates, use pointer
        if (typeRef.ResolvedSymbol is InterfaceSymbol or DelegateSymbol)
            return $"{MangleName(typeRef.ResolvedSymbol.FullName)}*";

        // For enum/struct, use name directly
        if (typeRef.ResolvedSymbol is EnumSymbol or StructSymbol)
            return typeRef.ResolvedSymbol.Name;

        // Namespace-qualified type without resolved symbol (e.g. generic instantiation
        // like "Windows.Foundation.Collections.IVector"): mangle the qualified name.
        if (typeRef.Name.Contains('.'))
            return $"{MangleName(typeRef.Name)}*";

        // Fallback: use the name as-is
        return typeRef.Name;
    }

    internal static string MangleName(string fullName)
    {
        return "__x_" + fullName.Replace(".", "_C");
    }

    private static string[] GetNamespaceParts(ISymbol symbol)
    {
        if (symbol.ContainingSymbol is NamespaceSymbol ns && ns.FullName.Length > 0)
            return ns.FullName.Split('.');
        return Array.Empty<string>();
    }

    private static string BuildParameterList(List<ParameterSymbol> parameters)
    {
        var parts = new List<string>();
        foreach (var p in parameters)
        {
            var cType = MapType(p.Type);
            if (p.Direction == ParameterDirection.Out)
                parts.Add($"/* [out] */ {cType}* {p.Name}");
            else if (p.Direction == ParameterDirection.RefConst)
                parts.Add($"/* [in] */ {cType}* {p.Name}");
            else
                parts.Add($"/* [in] */ {cType} {p.Name}");
        }
        return string.Join(", ", parts);
    }

    /// <summary>
    /// Generates a deterministic UUID v5 from the fully-qualified type name.
    /// </summary>
    internal static string GenerateUuid(string fullName)
    {
        // Use a fixed namespace UUID for MIDL types
        var namespaceId = new byte[]
        {
            0x6b, 0xa7, 0xb8, 0x10, 0x9d, 0xad, 0x11, 0xd1,
            0x80, 0xb4, 0x00, 0xc0, 0x4f, 0xd4, 0x30, 0xc8
        };
        var nameBytes = Encoding.UTF8.GetBytes(fullName);
        var input = new byte[namespaceId.Length + nameBytes.Length];
        Array.Copy(namespaceId, 0, input, 0, namespaceId.Length);
        Array.Copy(nameBytes, 0, input, namespaceId.Length, nameBytes.Length);

        var hash = SHA1.HashData(input);

        // Format as UUID v5
        hash[6] = (byte)((hash[6] & 0x0F) | 0x50); // version 5
        hash[8] = (byte)((hash[8] & 0x3F) | 0x80); // variant

        var guid = new Guid(new ReadOnlySpan<byte>(hash, 0, 16));
        return guid.ToString("D");
    }
}
