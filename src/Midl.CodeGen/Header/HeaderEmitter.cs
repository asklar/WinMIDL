using System.Security.Cryptography;
using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;
using Midl.Syntax;

namespace Midl.CodeGen.Header;

/// <summary>
/// Generates C/C++ header files from a MIDL compilation's symbol table.
/// </summary>
public class HeaderEmitter
{
    private static readonly Dictionary<string, string> TypeMap = new(StringComparer.Ordinal)
    {
        ["Int16"] = "INT16",
        ["Int32"] = "INT32",
        ["Int64"] = "INT64",
        ["UInt8"] = "BYTE",
        ["UInt16"] = "UINT16",
        ["UInt32"] = "UINT32",
        ["UInt64"] = "UINT64",
        ["Single"] = "FLOAT",
        ["Double"] = "DOUBLE",
        ["Boolean"] = "boolean",
        ["Char"] = "WCHAR",
        ["String"] = "HSTRING",
        ["Guid"] = "GUID",
        ["Object"] = "IInspectable*",
        ["void"] = "void",
        ["HRESULT"] = "HRESULT",
    };

    public string Emit(Compilation compilation)
    {
        var sb = new StringBuilder();
        var guardName = BuildGuardName(compilation);

        sb.AppendLine("/* Header auto-generated by MIDL compiler */");
        sb.AppendLine("#pragma once");
        sb.AppendLine();
        sb.AppendLine($"#ifndef {guardName}");
        sb.AppendLine($"#define {guardName}");
        sb.AppendLine();

        // Collect all types (exclude imported/external types)
        var allTypes = compilation.GetAllTypes().Where(t => !t.IsExternal).ToList();
        MidlTrace.CodeGen($"Generating header, {allTypes.Count} types");

        // Emit system includes based on types used
        EmitSystemIncludes(sb, allTypes);

        // Forward declarations for external types referenced but not defined here
        EmitExternalForwardDeclarations(sb, allTypes);

        // Forward declarations
        EmitForwardDeclarations(sb, allTypes);

        // Type definitions grouped by kind: enums, structs, delegates, interfaces, runtime classes
        foreach (var symbol in allTypes)
        {
            switch (symbol)
            {
                case EnumSymbol e:
                    EmitEnum(sb, e);
                    break;
                case StructSymbol s:
                    EmitStruct(sb, s);
                    break;
                case DelegateSymbol d:
                    EmitDelegate(sb, d);
                    break;
                case InterfaceSymbol iface:
                    EmitInterface(sb, iface);
                    break;
                case RuntimeClassSymbol rc:
                    EmitRuntimeClass(sb, rc);
                    break;
            }
        }

        sb.AppendLine($"#endif // {guardName}");

        return sb.ToString();
    }

    public void EmitToFile(Compilation compilation, string outputPath)
    {
        var content = Emit(compilation);
        File.WriteAllText(outputPath, content, Encoding.UTF8);
    }

    private static string BuildGuardName(Compilation compilation)
    {
        // Use the first namespace found, or a generic name
        var allTypes = compilation.GetAllTypes().Where(t => !t.IsExternal).ToList();
        string nsName = "";
        foreach (var t in allTypes)
        {
            if (t.ContainingSymbol is NamespaceSymbol ns && ns.FullName.Length > 0)
            {
                nsName = ns.FullName;
                break;
            }
        }

        if (string.IsNullOrEmpty(nsName))
            nsName = "Generated";

        var safeName = nsName.Replace(".", "_");
        return $"__{safeName}_h__";
    }

    private static void EmitSystemIncludes(StringBuilder sb, List<ISymbol> allTypes)
    {
        bool needsEventToken = false;
        foreach (var symbol in allTypes)
        {
            if (symbol is InterfaceSymbol iface)
            {
                foreach (var m in iface.Members)
                {
                    if (m is EventSymbol) { needsEventToken = true; break; }
                    if (m is MethodSymbol method)
                    {
                        if (method.ReturnType?.Name == "EventRegistrationToken") { needsEventToken = true; break; }
                        if (method.Parameters.Any(p => p.Type.Name == "EventRegistrationToken")) { needsEventToken = true; break; }
                    }
                }
            }
            if (needsEventToken) break;
        }

        if (needsEventToken)
        {
            sb.AppendLine("#include <eventtoken.h>");
            sb.AppendLine();
        }
    }

    private static void EmitExternalForwardDeclarations(StringBuilder sb, List<ISymbol> allTypes)
    {
        // Collect external type names referenced by local interfaces
        var externalTypes = new HashSet<string>();
        foreach (var symbol in allTypes)
        {
            if (symbol is InterfaceSymbol iface)
            {
                foreach (var m in iface.Members)
                {
                    CollectExternalTypeRefs(m, externalTypes);
                }
            }
            else if (symbol is RuntimeClassSymbol rc)
            {
                foreach (var m in rc.Members)
                {
                    CollectExternalTypeRefs(m, externalTypes);
                }
            }
        }

        if (externalTypes.Count > 0)
        {
            sb.AppendLine("// External interface definitions (for IUnknown* upcast in marshal calls)");
            foreach (var typeName in externalTypes.OrderBy(t => t))
            {
                sb.AppendLine($"#ifndef __{typeName}_DEFINED__");
                sb.AppendLine($"#define __{typeName}_DEFINED__");
                sb.AppendLine($"struct {typeName} : public IInspectable {{}};");
                sb.AppendLine($"#endif");
            }
            sb.AppendLine();
        }
    }

    private static void CollectExternalTypeRefs(ISymbol member, HashSet<string> externalTypes)
    {
        void CheckTypeRef(TypeRef? typeRef)
        {
            // Skip parameterized instantiations — they project as IInspectable*
            if (typeRef?.TypeArguments.Count > 0)
                return;

            if (typeRef?.ResolvedSymbol is InterfaceSymbol or DelegateSymbol && typeRef.ResolvedSymbol.IsExternal)
            {
                externalTypes.Add(MangleName(typeRef.ResolvedSymbol.FullName));
            }
        }

        if (member is MethodSymbol method)
        {
            CheckTypeRef(method.ReturnType);
            foreach (var p in method.Parameters)
                CheckTypeRef(p.Type);
        }
        else if (member is PropertySymbol prop)
        {
            CheckTypeRef(prop.Type);
        }
        else if (member is EventSymbol evt)
        {
            CheckTypeRef(evt.DelegateType);
        }
    }

    /// <summary>
    /// Maps a mangled external type name to its Windows SDK ABI header.
    /// </summary>
    private static string? GetAbiHeaderForType(string mangledName)
    {
        // Map namespace prefix to SDK header
        // __x_Windows_Foundation_ → windows.foundation.h
        // __x_Windows_Foundation_Collections_ → windows.foundation.collections.h
        // __x_Windows_UI_Xaml_ → windows.ui.xaml.h
        // __x_Microsoft_UI_Xaml_ → microsoft.ui.xaml.h
        if (mangledName.StartsWith("__x_Windows_Foundation_Collections_"))
            return "windows.foundation.collections.h";
        if (mangledName.StartsWith("__x_Windows_Foundation_"))
            return "windows.foundation.h";
        if (mangledName.StartsWith("__x_Windows_UI_"))
        {
            var parts = mangledName.Split('_');
            // __x_Windows_UI_Xaml_Controls_ → windows.ui.xaml.controls.h
            // Take namespace segments up to the type name
            var nsParts = new List<string>();
            for (int i = 2; i < parts.Length; i++) // skip __x
            {
                if (parts[i].Length > 0 && char.IsUpper(parts[i][0]))
                    nsParts.Add(parts[i].ToLowerInvariant());
                else
                    break;
            }
            if (nsParts.Count >= 2)
                return string.Join(".", nsParts) + ".h";
        }
        if (mangledName.StartsWith("__x_Microsoft_"))
        {
            // Similar mapping for WinAppSDK
            if (mangledName.StartsWith("__x_Microsoft_UI_Xaml_"))
                return "microsoft.ui.xaml.h";
            if (mangledName.StartsWith("__x_Microsoft_UI_"))
                return "microsoft.ui.h";
        }

        return null;
    }

    private static void EmitForwardDeclarations(StringBuilder sb, List<ISymbol> allTypes)
    {
        var hasForward = false;
        foreach (var symbol in allTypes)
        {
            if (symbol is InterfaceSymbol iface)
            {
                if (!hasForward)
                {
                    sb.AppendLine("// Forward declarations");
                    hasForward = true;
                }
                sb.AppendLine($"typedef interface {MangleName(iface.FullName)} {MangleName(iface.FullName)};");
            }
        }
        if (hasForward)
            sb.AppendLine();
    }

    private static void EmitEnum(StringBuilder sb, EnumSymbol e)
    {
        var underlyingCType = e.UnderlyingType == "UInt32" ? "UINT32" : "INT32";
        sb.AppendLine($"enum {e.Name} : {underlyingCType}");
        sb.AppendLine("{");
        for (int i = 0; i < e.EnumMembers.Count; i++)
        {
            var member = e.EnumMembers[i];
            sb.AppendLine($"    {e.Name}_{member.Name} = {i},");
        }
        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitStruct(StringBuilder sb, StructSymbol s)
    {
        sb.AppendLine($"struct {s.Name}");
        sb.AppendLine("{");
        foreach (var field in s.Fields)
        {
            sb.AppendLine($"    {MapType(field.Type)} {field.Name};");
        }
        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitDelegate(StringBuilder sb, DelegateSymbol d)
    {
        var mangledName = MangleName(d.FullName);
        var uuid = d.Uuid?.ToString("D") ?? GenerateUuid(d.FullName);

        sb.AppendLine($"EXTERN_C const IID IID_{mangledName};");
        sb.AppendLine();
        sb.AppendLine($"MIDL_INTERFACE(\"{uuid}\")");
        sb.AppendLine($"{mangledName} : public IUnknown");
        sb.AppendLine("{");
        sb.AppendLine("public:");

        // Delegate has an Invoke method
        var returnType = MapType(d.ReturnType);
        var paramList = BuildParameterList(d.Parameters);
        sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE Invoke({paramList}) = 0;");

        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void EmitInterface(StringBuilder sb, InterfaceSymbol iface)
    {
        var mangledName = MangleName(iface.FullName);
        var uuid = iface.Uuid?.ToString("D") ?? GenerateUuid(iface.FullName);
        var guard = $"____{mangledName.TrimStart('_')}_INTERFACE_DEFINED__";

        sb.AppendLine($"#ifndef {guard}");
        sb.AppendLine($"#define {guard}");
        sb.AppendLine();
        sb.AppendLine($"EXTERN_C const IID IID_{mangledName};");
        sb.AppendLine();
        sb.AppendLine($"MIDL_INTERFACE(\"{uuid}\")");
        sb.AppendLine($"{mangledName} : public IInspectable");
        sb.AppendLine("{");
        sb.AppendLine("public:");

        foreach (var member in iface.Members)
        {
            switch (member)
            {
                case PropertySymbol prop:
                    EmitPropertyMethods(sb, prop);
                    break;
                case MethodSymbol method:
                    EmitMethod(sb, method);
                    break;
                case EventSymbol evt:
                    EmitEventMethods(sb, evt);
                    break;
            }
        }

        sb.AppendLine("};");
        sb.AppendLine();
        sb.AppendLine($"#endif // {guard}");
        sb.AppendLine();
    }

    private static void EmitPropertyMethods(StringBuilder sb, PropertySymbol prop)
    {
        var cType = MapType(prop.Type);
        if (prop.HasGetter)
        {
            sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE get_{prop.Name}(/* [out, retval] */ {cType}* value) = 0;");
        }
        if (prop.HasSetter)
        {
            sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE put_{prop.Name}(/* [in] */ {cType} value) = 0;");
        }
    }

    private static void EmitMethod(StringBuilder sb, MethodSymbol method)
    {
        var paramParts = new List<string>();
        foreach (var p in method.Parameters)
        {
            if (p.IsArray)
            {
                ExpandArrayParam(paramParts, p);
            }
            else
            {
                var cType = MapType(p.Type);
                if (p.Direction == ParameterDirection.Out)
                    paramParts.Add($"/* [out] */ {cType}* {p.Name}");
                else if (p.Direction == ParameterDirection.RefConst)
                    paramParts.Add($"/* [in] */ {cType}* {p.Name}");
                else
                    paramParts.Add($"/* [in] */ {cType} {p.Name}");
            }
        }

        // If non-void return, add retval out param
        if (method.ReturnType.Name != "void")
        {
            if (method.ReturnType.IsArray)
            {
                var elemType = MapType(Midl.CodeGen.Proxy.WireFormat.ElementType(method.ReturnType));
                paramParts.Add($"/* [out, retval] */ UINT32* __returnSize");
                paramParts.Add($"/* [out, retval] */ {elemType}** __returnItems");
            }
            else
            {
                var retType = MapType(method.ReturnType);
                paramParts.Add($"/* [out, retval] */ {retType}* returnValue");
            }
        }

        var paramStr = string.Join(", ", paramParts);
        sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE {method.Name}({paramStr}) = 0;");
    }

    private static void ExpandArrayParam(List<string> parts, ParameterSymbol p)
    {
        var elemType = MapType(Midl.CodeGen.Proxy.WireFormat.ElementType(p.Type));
        switch (p.Direction)
        {
            case ParameterDirection.In:
                // PassArray: UINT32 __itemsSize, T* items
                parts.Add($"/* [in] */ UINT32 __{p.Name}Size");
                parts.Add($"/* [in] */ {elemType}* {p.Name}");
                break;
            case ParameterDirection.Out:
                // ReceiveArray: UINT32* __itemsSize, T** items
                parts.Add($"/* [out] */ UINT32* __{p.Name}Size");
                parts.Add($"/* [out] */ {elemType}** {p.Name}");
                break;
            case ParameterDirection.Ref:
                // FillArray: UINT32 __itemsCapacity, T* items, UINT32* __itemsActual
                parts.Add($"/* [in] */ UINT32 __{p.Name}Capacity");
                parts.Add($"/* [out] */ {elemType}* {p.Name}");
                parts.Add($"/* [out] */ UINT32* __{p.Name}Actual");
                break;
            default:
                // Fallback: treat like PassArray
                parts.Add($"/* [in] */ UINT32 __{p.Name}Size");
                parts.Add($"/* [in] */ {elemType}* {p.Name}");
                break;
        }
    }

    private static void EmitEventMethods(StringBuilder sb, EventSymbol evt)
    {
        sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE add_{evt.Name}(/* [in] */ {MapType(evt.DelegateType)} handler, /* [out, retval] */ EventRegistrationToken* token) = 0;");
        sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE remove_{evt.Name}(/* [in] */ EventRegistrationToken token) = 0;");
    }

    private static void EmitRuntimeClass(StringBuilder sb, RuntimeClassSymbol rc)
    {
        var fullName = rc.FullName;
        var activationName = fullName.Replace(".", "_");
        sb.AppendLine($"extern const __declspec(selectany) _Null_terminated_ WCHAR RuntimeClass_{activationName}[] = L\"{fullName}\";");
        sb.AppendLine();
    }

    internal static string MapType(TypeRef typeRef)
    {
        if (typeRef.Name == "void")
            return "void";

        if (TypeMap.TryGetValue(typeRef.Name, out var mapped))
            return mapped;

        // Parameterized interface/delegate instantiations (IReference<T>, EventHandler<T>, etc.)
        // are projected as IInspectable* at the ABI level
        if (typeRef.TypeArguments.Count > 0 && typeRef.ResolvedSymbol is InterfaceSymbol or DelegateSymbol)
            return "IInspectable*";

        // For resolved user-defined types that are interfaces/delegates, use pointer
        if (typeRef.ResolvedSymbol is InterfaceSymbol or DelegateSymbol)
            return $"{MangleName(typeRef.ResolvedSymbol.FullName)}*";

        // RuntimeClass: ABI uses the default interface pointer type
        if (typeRef.ResolvedSymbol is RuntimeClassSymbol rc && rc.DefaultInterface is { } defaultIface)
            return $"{MangleName(defaultIface.FullName)}*";

        // For enum/struct, use name directly
        if (typeRef.ResolvedSymbol is EnumSymbol or StructSymbol)
            return typeRef.ResolvedSymbol.Name;

        // Fallback: use the name as-is
        return typeRef.Name;
    }

    internal static string MangleName(string fullName)
    {
        return "__x_" + fullName.Replace(".", "_");
    }

    private static string BuildParameterList(List<ParameterSymbol> parameters)
    {
        var parts = new List<string>();
        foreach (var p in parameters)
        {
            if (p.IsArray)
            {
                ExpandArrayParam(parts, p);
            }
            else
            {
                var cType = MapType(p.Type);
                if (p.Direction == ParameterDirection.Out)
                    parts.Add($"/* [out] */ {cType}* {p.Name}");
                else if (p.Direction == ParameterDirection.RefConst)
                    parts.Add($"/* [in] */ {cType}* {p.Name}");
                else
                    parts.Add($"/* [in] */ {cType} {p.Name}");
            }
        }
        return string.Join(", ", parts);
    }

    /// <summary>
    /// Generates a deterministic UUID v5 from the fully-qualified type name.
    /// </summary>
    internal static string GenerateUuid(string fullName)
    {
        // Use a fixed namespace UUID for MIDL types
        var namespaceId = new byte[]
        {
            0x6b, 0xa7, 0xb8, 0x10, 0x9d, 0xad, 0x11, 0xd1,
            0x80, 0xb4, 0x00, 0xc0, 0x4f, 0xd4, 0x30, 0xc8
        };
        var nameBytes = Encoding.UTF8.GetBytes(fullName);
        var input = new byte[namespaceId.Length + nameBytes.Length];
        Array.Copy(namespaceId, 0, input, 0, namespaceId.Length);
        Array.Copy(nameBytes, 0, input, namespaceId.Length, nameBytes.Length);

        var hash = SHA1.HashData(input);

        // Format as UUID v5
        hash[6] = (byte)((hash[6] & 0x0F) | 0x50); // version 5
        hash[8] = (byte)((hash[8] & 0x3F) | 0x80); // variant

        var guid = new Guid(new ReadOnlySpan<byte>(hash, 0, 16));
        return guid.ToString("D");
    }
}
