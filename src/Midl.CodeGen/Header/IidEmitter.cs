using System.Text;
using Midl.Analysis;
using Midl.Analysis.Symbols;

namespace Midl.CodeGen.Header;

/// <summary>
/// Generates an IID definition file (_i.c) containing EXTERN_C IID constants.
/// </summary>
public class IidEmitter
{
    public string Emit(Compilation compilation)
    {
        var sb = new StringBuilder();
        sb.AppendLine("/* IID definitions auto-generated by MIDL compiler */");
        sb.AppendLine();

        foreach (var symbol in compilation.GetAllTypes())
        {
            switch (symbol)
            {
                case InterfaceSymbol iface:
                    EmitIid(sb, iface.FullName);
                    break;
                case DelegateSymbol d:
                    EmitIid(sb, d.FullName);
                    break;
            }
        }

        return sb.ToString();
    }

    public void EmitToFile(Compilation compilation, string outputPath)
    {
        var content = Emit(compilation);
        File.WriteAllText(outputPath, content, Encoding.UTF8);
    }

    private static void EmitIid(StringBuilder sb, string fullName)
    {
        var mangledName = HeaderEmitter.MangleName(fullName);
        var uuid = HeaderEmitter.GenerateUuid(fullName);
        var parts = uuid.Split('-');

        // Parse UUID parts into hex components
        // Format: {0x12345678, 0x1234, 0x1234, {0x12, 0x34, 0x12, 0x34, 0x56, 0x78, 0x9a, 0xbc}}
        var data1 = parts[0];
        var data2 = parts[1];
        var data3 = parts[2];
        var data4Str = parts[3] + parts[4]; // 16 hex chars

        var data4Parts = new string[8];
        for (int i = 0; i < 8; i++)
            data4Parts[i] = $"0x{data4Str.Substring(i * 2, 2)}";

        sb.AppendLine($"// {{{uuid}}}");
        sb.AppendLine($"EXTERN_C const IID IID_{mangledName} = {{0x{data1}, 0x{data2}, 0x{data3}, {{{string.Join(", ", data4Parts)}}}}};");
        sb.AppendLine();
    }
}
